def logo_pages(path):
    """A 128 x 64 boot logo PNG as the radio stores it (8 pages of 128 column
    bytes, bit 0 on top): dark opaque pixels lit. Needs Pillow."""
    from PIL import Image
    im = Image.open(path).convert("RGBA")
    px = im.load()
    return lcd_pages([[int(px[x, y][3] > 127 and sum(px[x, y][:3]) < 384) for x in range(128)]
                      for y in range(64)])


def tones_audio(*tones, fs=48000, seconds=6):
    """Steady tones (Hz, ADC LSB peak) around the 2048 bias."""
    return [int(2048 + sum(a * math.sin(2 * math.pi * f * i / fs) for f, a in tones))
            for i in range(fs * seconds)], fs


MORSE = {"A": ".-", "C": "-.-.", "D": "-..", "E": ".", "F": "..-.", "H": "....", "K": "-.-",
         "N": "-.", "Q": "--.-", "W": ".--", "4": "....-"}


def cw_rssi(text, wpm=18, start_ms=2000):
    """A keyed carrier, as CW Decode measures it (RSSI), from start_ms on."""
    dit = 1200.0 / wpm
    spans, t = [], start_ms
    for word in text.split():
        for ch in word:
            for mark in MORSE[ch]:
                length = dit if mark == "." else 3 * dit
                spans.append((t, t + length))
                t += length + dit
            t += 2 * dit
        t += 4 * dit
    def rssi(t, rng, f=None):
        on = any(a <= t < b for a, b in spans)
        return (-78 if on else -121) + rng.gauss(0, 1.2)
    rssi.end = t
    return rssi


def steady_rssi(dbm):
    """A station heard at a steady level (the decoders show the live RSSI)."""
    return lambda t, rng, f=None: dbm + rng.gauss(0, 1.2)


def burst_rssi(start_ms, length_ms, dbm=-76, floor=-119):
    """A carrier from start_ms for length_ms: EPIRB 406 triggers on its rise."""
    return lambda t, rng, f=None: (dbm if start_ms <= t < start_ms + length_ms else floor) + rng.gauss(0, 1)


def band_rssi(t, rng, f):
    """What Spectrum3D's sweep reads around 145.500: four carriers, slowly
    fading, over a -122 dBm floor (f and widths in 10 Hz units)."""
    level = -122.0
    for centre, peak, width in ((14545000, -70, 900), (14550000, -84, 700),
                                (14553750, -95, 600), (14561250, -101, 500)):
        peak += 3 * math.sin(t / 700 + centre)
        level = max(level, peak - 6 * ((f - centre) / width) ** 2)
    return level + rng.gauss(0, 1.5)


def presses(start_ms, *keys, step=250, hold=120):
    """Key presses one after the other from start_ms: (time, code, duration)."""
    return [(start_ms + i * step, KEYS[k], hold) for i, k in enumerate(keys)]


