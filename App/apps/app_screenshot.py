def parse_keys(s):
    out = []
    for item in filter(None, s.split(",")):
        p = item.split(":")
        out.append((float(p[0]), KEYS[p[1].upper()], float(p[2]) if len(p) > 2 else 100.0))
    return out


def find_app(name):
    d = os.path.join(HERE, name.lower())
    if os.path.isdir(d):
        return d
    if os.path.isdir(name):
        return name
    sys.exit(f"{name}: no such app folder in {HERE}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("apps", nargs="*")
    ap.add_argument("--at", help="capture times in ms, comma-separated")
    ap.add_argument("--keys", help="TIME:KEY[:DURATION],...")
    ap.add_argument("--firmware", default=FIRMWARE)
    ap.add_argument("--out", default=".")
    ap.add_argument("--scale", type=int, default=4)
    ap.add_argument("--plain", action="store_true", help="black on white, no frame or grid")
    ap.add_argument("--catalog", metavar="FILE", help="update the UV Studio catalog screens (app-screens.js)")
    ap.add_argument("--viewer", metavar="ID=PNG", action="append", default=[],
                    help="with --catalog: app ID's screen from a Live Viewer screenshot")
    a = ap.parse_args()
    if a.viewer and not a.catalog:
        ap.error("--viewer needs --catalog")
    if not a.catalog:
        os.makedirs(a.out, exist_ok=True)
    screens = {}
    for name in a.apps:
        d = find_app(name)
        app = os.path.basename(os.path.normpath(d))
        sc = dict(SCENARIOS.get(app, dict(shots=[("1s", 1000), ("3s", 3000)])))
        if a.at:
            sc["shots"] = [(f"{t}ms", float(t)) for t in a.at.split(",")]
        if a.keys is not None:
            sc["keys"] = parse_keys(a.keys)
        print(f"{app}:")
        e = Emu(d, a.firmware, sc).run()
        if a.catalog:
            card = sc.get("card", sc["shots"][-1][0])
            rows = next(r for label, t, r in e.taken if label == card)
            screens[catalog_id(d)] = lcd_pages(rows)
            print(f"  {catalog_id(d)} ({card})")
            continue
        for label, t, rows in e.taken:
            path = os.path.join(a.out, f"{app}-{label}.png")
            png(rows, path, scale=a.scale, plain=a.plain)
            print(f"  {path} (T={t:.0f} ms)")
        if e.returned:
            print("  app_main returned")
    for item in a.viewer:
        app_id, path = item.split("=", 1)
        screens[app_id] = viewer_frame(path)
        print(f"{app_id}: {path}")
    if a.catalog:
        write_catalog(a.catalog, screens)
        print(f"{a.catalog}: {len(screens)} screens updated")


if __name__ == "__main__":
    main()
