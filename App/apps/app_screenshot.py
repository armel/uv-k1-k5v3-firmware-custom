sys.dont_write_bytecode = True   # the apps' test models are imported: no __pycache__ in the tree
FIRMWARE = os.path.join(HERE, "..", "..", "build", "Fusion", "f4hwn.fusion.elf")
F4HWN_LOGO = os.path.join(HERE, "..", "..", "archive", "f4hwn.logo.v2.png")
LOGO_ADDR = 0x011008             # ui/welcome.c LOGO_BITMAP_ADDR: the boot logo in external flash

