def aprs_home(lat_d, lat_m100, lon_d, lon_m100, hemi=0):
    """APRS TX profile prefix as APRS Edit saves it (aprs_profile.h)."""
    digits = [int(c) for c in f"{lat_d:02d}{lat_m100:04d}{lon_d:03d}{lon_m100:04d}"]
    return struct.pack("<I", 0x37435041) + bytes([0, 0, 0, hemi]) + bytes(digits)


def fox_rssi(t, rng, f=None):
    """A fox approached: -118 dBm rising to about -70 dBm, with fading."""
    return min(-118 + t / 120, -70) + rng.gauss(0, 2.5)


def cas(deg, minutes):
    return int(round((deg * 60 + minutes) * 6000))


# A sample radiosonde frame, handed back as GeoNav does on EXIT: the sonde apps
# then show it again (their sonde_info.h, the first APP_HANDOFF_MAX bytes).
SONDE_POS = (cas(48, 47.04), cas(2, 6.09), 12345)      # rising NW of Paris, 12 345 m


def sonde_rs41(sid):
    """RS41 sonde_info_t: position, velocity, battery (POS | ALT | ID)."""
    return struct.pack("<12siiihHHBB", sid.encode(), *SONDE_POS, 52, 14, 72, 1 | 2 | 32, 29)


def sonde_meteo(sid, flags):
    """M10 / M20 / MRZ sonde_info_t: position, velocity, temperature, humidity."""
    return struct.pack("<12siiihhBBBB", sid.encode(), *SONDE_POS, 52, -485, 14, 72, flags, 23)


def sonde_rssi(t, rng, f=None):
    return -84 + rng.gauss(0, 1.5)


