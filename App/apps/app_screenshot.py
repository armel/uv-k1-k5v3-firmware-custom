APP_CONFIG_PROXY_MAGIC = 0x31505843  # "CXP1", app_config_proxy.h

SYST_LOAD, SYST_VAL = 0xE000E014, 0xE000E018
SYST_RELOAD = 479999             # the firmware's 10 ms SysTick at 48 MHz
SYST_READ_MS = 0.03              # a busy-wait loop advances time on each read

APP_SERIAL_OK, APP_SERIAL_HOST = 0x01, 0x02          # app_api.h
REG_0C, REG_0C_SQUELCH = 0x0C, 0x02                  # BK4829: bit 1, squelch open
ADC_BASE, ADC_SR, ADC_DR = 0x40012400, 0x00, 0x50   # apps that read PA4 themselves
ADC_SR_EOC = 2

LCD_PAGE = 131                   # bytes per page for lcd_feed: 3 commands + 128 data
BLIT_PAGE_MS = 1.5               # one LCD page at SPI 750 kHz


def api_fields():
    """(name, is_function) of every app_api_t field after the 4-byte prefix,
    in order, read from app_api.h."""
    src = open(os.path.join(HERE, "app_api.h")).read()
    body = src[src.index("typedef struct app_api {"):src.index("} app_api_t;")]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    body = body.split("{", 1)[1]
    out = []
    for decl in body.split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        m = re.search(r"\(\s*\*\s*(\w+)\s*\)", decl)
        if m:
            out.append((m.group(1), True))
        else:
            out.append((re.findall(r"\w+", decl)[-1], False))
    assert [n for n, _ in out[:3]] == ["abi_major", "api_level", "api_size"], out[:3]
    return out[3:]


def proxy_block(assets, apps_dir):
    """The block another app's assets lend through a config proxy
    (app_config_proxy.h): what the loader serves to cfg_load. None without one."""
    if len(assets) < 28 or struct.unpack_from("<I", assets)[0] != APP_CONFIG_PROXY_MAGIC:
        return None
    name = assets[4:20].split(b"\0")[0]
    off, n = struct.unpack_from("<HB", assets, 20)
    for d in sorted(glob.glob(os.path.join(apps_dir, "*", ""))):
        for app in glob.glob(os.path.join(d, "*.app")):
            with open(app, "rb") as f:
                head = f.read(64)
            target = glob.glob(os.path.join(d, "*_assets.bin"))
            if head[20:36].split(b"\0")[0] == name and target:
                return open(target[0], "rb").read()[off:off + n]
    return None


def catalog_id(app_dir):
    """UV Studio's id of the app: its .app file name, lowercase alphanumerics."""
    apps = glob.glob(os.path.join(app_dir, "*.app"))
    name = os.path.basename(apps[0])[:-4] if apps else os.path.basename(os.path.normpath(app_dir))
    return re.sub(r"[^a-z0-9]", "", name.lower())


def load_segments(u, path):
    with open(path, "rb") as f:
        elf = ELFFile(f)
        segs = [(s["p_vaddr"], s.data()) for s in elf.iter_segments()
                if s["p_type"] == "PT_LOAD" and s["p_filesz"]]
        sym = {s.name: s["st_value"] for s in elf.get_section_by_name(".symtab").iter_symbols()}
        secs = {s.name: (s["sh_addr"], s.data() if s["sh_type"] != "SHT_NOBITS" else b"")
                for s in elf.iter_sections()}
    return segs, sym, secs


class Lcd:
    """The screen as the radio shows it: pages 0 (status) to 7."""
    def __init__(self):
        self.pages = [bytes(128)] * 8

    def rows(self):
        return [[self.pages[y >> 3][x] >> (y & 7) & 1 for x in range(128)] for y in range(64)]


def png(rows, path, scale=4, gap=16, plain=False):
    """LCD-look PNG (the colors of af_lcd.py), or a plain black-on-white one."""
    if plain:
        bg, fg, grid, frame, gap = (255, 255, 255), (0, 0, 0), (255, 255, 255), (255, 255, 255), 0
    else:
        bg, fg, grid, frame = (214, 216, 230), (38, 38, 70), (200, 202, 218), (60, 60, 60)
    cw, ch = 128 * scale, 64 * scale
    tw, th = cw + 2 * gap, ch + 2 * gap
    lines = []
    for y in range(th):
        line = bytearray()
        for x in range(tw):
            px, py = x - gap, y - gap
            if 0 <= px < cw and 0 <= py < ch:
                g = scale > 2 and (px % scale == scale - 1 or py % scale == scale - 1)
                line += bytes(fg if rows[py // scale][px // scale] else (grid if g else bg))
            else:
                line += bytes(frame)
        lines.append(b"\0" + bytes(line))
    write_png(path, tw, th, 2, lines)


def lcd_pages(rows):
    """The 1024 bytes of the LCD: 8 pages of 128 column bytes, bit 0 on top."""
    out = bytearray(1024)
    for y in range(64):
        for x in range(128):
            if rows[y][x]:
                out[(y >> 3) * 128 + x] |= 1 << (y & 7)
    return bytes(out)


def viewer_frame(path):
    """The 1024 LCD bytes of a Live Viewer screenshot: 128 x 64 cells, each
    read at its centre against the glass in its corner (the gap of the LCD
    effect; without it, the majority of cells, unlit on most screens)."""
    from PIL import Image
    im = Image.open(path).convert("L")
    px, cw, ch = im.load(), im.width / 128, im.height / 64
    corners = sorted(px[int((x + 1) * cw) - 1, int((y + 1) * ch) - 1] for y in range(64) for x in range(128))
    glass = corners[len(corners) // 2]
    centre = [[px[int(x * cw + (cw - 1) / 2), int(y * ch + (ch - 1) / 2)] for x in range(128)]
              for y in range(64)]
    far = max(abs(v - glass) for row in centre for v in row)
    return lcd_pages([[int(abs(v - glass) > far / 2) for v in row] for row in centre])


def write_catalog(path, screens):
    """Merge {catalog id: 1024 LCD bytes} into UV Studio's app-screens.js."""
    old = {}
    if os.path.exists(path):
        old = dict(re.findall(r"^ {4}(\w+): '([A-Za-z0-9+/=]+)'", open(path).read(), re.M))
    old.update({k: base64.b64encode(v).decode() for k, v in screens.items()})
    body = ",\n".join(f"    {k}: '{old[k]}'" for k in sorted(old))
    with open(path, "w") as f:
        f.write(CATALOG_HEAD + body + "\n" + CATALOG_TAIL)


def write_png(path, w, h, color_type, lines):
    def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d))
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, color_type, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(b"".join(lines), 9)) + chunk(b"IEND", b""))


class Emu:
    def __init__(self, app_dir, firmware, scenario):
        self.sc = scenario
        self.T = 0.0
        self.lcd = Lcd()
        self.feed = 0
        self.keys = scenario.get("keys", [])
        self.shots = sorted(scenario["shots"], key=lambda s: s[1])
        self.taken = []
        self.bk = {}
        self.rng = random.Random(1)
        self.xs = 0x2545F491
        self.unknown = set()
        self.returned = False
        # Audio for af_capture_sample: ADC samples at fs from audio_at ms on.
        # Busy-wait loops read the cycle clock: a quarter of a sample period per
        # read keeps an audio decoder on its sampling grid.
        audio = scenario["audio"]() if "audio" in scenario else ([], 0)
        self.audio, self.fs = audio[:2]
        # the carrier's bursts, ms from audio_at (default: the whole audio)
        self.bursts = audio[2] if len(audio) > 2 else [(0, len(self.audio) * 1000 / self.fs if self.fs else 0)]
        self.audio_at = scenario.get("audio_at", 500.0)
        self.cycle_ms = min(0.03, 250.0 / self.fs) if self.fs else 0.03

        elfs = [p for p in glob.glob(os.path.join(app_dir, "*.elf"))]
        if len(elfs) != 1:
            sys.exit(f"{app_dir}: expected one built .elf, found {len(elfs)}")
        assets = glob.glob(os.path.join(app_dir, "*_assets.bin"))
        self.assets = open(assets[0], "rb").read() if assets else b""
        self.proxy = proxy_block(self.assets, os.path.dirname(os.path.normpath(app_dir)))

        u = self.u = Uc(UC_ARCH_ARM, UC_MODE_THUMB | UC_MODE_MCLASS)
        u.mem_map(FLASH, FLASH_SZ)
        u.mem_map(RAM, RAM_SZ)
        u.mem_map(0x40000000, 0x30000)         # APB/AHB peripherals: writes go nowhere
        u.mem_map(0x50000000, 0x2000)          # GPIO
        u.mem_map(0xE0000000, 0x100000)        # system control space
        u.mem_map(0x1FFF0000, 0x10000)         # system memory: UID, flash size (zeros)
        u.mem_write(SYST_LOAD, struct.pack("<I", SYST_RELOAD))
        u.hook_add(UC_HOOK_MEM_READ, self.on_systick, begin=SYST_VAL, end=SYST_VAL + 3)
        u.hook_add(UC_HOOK_MEM_READ, self.on_adc, begin=ADC_BASE, end=ADC_BASE + ADC_DR + 3)

        segs, self.fw, secs = load_segments(u, firmware)
        fwa_addr, self.fwa = secs.get(".fw_assets", (0x90000000, b""))
        self.fwa_addr = fwa_addr
        for addr, data in segs:
            if addr >> 28 == 9:
                continue                       # .fw_assets lives in external flash
            u.mem_write(addr, data)
        vma = self.fw["__mb_workspace_start"]
        app_segs, self.app, _ = load_segments(u, elfs[0])
        if self.app.get("APP_VMA", vma) != vma:
            sys.exit(f"{elfs[0]}: APP_VMA {self.app['APP_VMA']:#x} != firmware overlay {vma:#x}, rebuild the app")
        u.mem_write(vma, bytes(OVERLAY_SZ))    # the loader zeroes the overlay (bss)
        for addr, data in app_segs:
            u.mem_write(addr, data)

        # The firmware's asset readers go to the external flash: patch them to
        # "bx lr" and copy from the .fw_assets section in the hook instead.
        self.patched = {}
        for name in ("FW_ASSETS_Read", "FW_ASSETS_ReadStr"):
            if name in self.fw:
                a = self.fw[name] & ~1
                u.mem_write(a, b"\x70\x47")
                self.patched[a] = name

        # A plausible status line: battery 5 bars and its percentage.
        for name, fmt, v in (("gBatteryDisplayLevel", "<B", 5), ("gBatteryVoltageAverage", "<H", 790),
                             ("gSetting_battery_text", "<B", 2)):
            if name in self.fw:
                u.mem_write(self.fw[name], struct.pack(fmt, v))

        # The stubbed copy of the firmware's app_api table.
        fields = api_fields()
        table = self.fw["app_api"]
        head = bytes(u.mem_read(table, 4))
        size = struct.unpack("<H", head[2:])[0]
        if size != 4 + 4 * len(fields):
            sys.exit(f"app_api.h has {len(fields)} services but the firmware table is {size} bytes: "
                     "rebuild the firmware")
        real = bytes(u.mem_read(table, size))
        tab = bytearray(head)
        self.stubs = {}
        self.fb = self.sl = None
        for i, (name, fn) in enumerate(fields):
            ptr = struct.unpack_from("<I", real, 4 + 4 * i)[0]
            if name == "fb":
                self.fb = ptr
            elif name == "status_line":
                self.sl = ptr
            if fn and ptr and name not in REAL:
                a = STUB + 4 * i
                u.mem_write(a, b"\x70\x47\x00\xbf")
                self.stubs[a] = name
                ptr = a | 1
            tab += struct.pack("<I", ptr)
        u.mem_write(API, bytes(tab))
        u.mem_write(MAGIC, b"\x00\xbf\x00\xbf")
        u.hook_add(UC_HOOK_CODE, self.on_stub, begin=STUB, end=STUB + 4 * len(fields))
        for a in self.patched:
            u.hook_add(UC_HOOK_CODE, self.on_patched, begin=a, end=a + 1)
        self.t_end = self.shots[-1][1] + 50

    # ---- helpers ----
    def r(self, n):
        return self.u.reg_read((UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3)[n])

    def ret(self, v, hi=None):
        self.u.reg_write(UC_ARM_REG_R0, v & 0xFFFFFFFF)
        if hi is not None:
            self.u.reg_write(UC_ARM_REG_R1, hi & 0xFFFFFFFF)

    def page(self, p):
        if p == 0:
            self.lcd.pages[0] = bytes(self.u.mem_read(self.sl, 128))
        else:
            self.lcd.pages[p] = bytes(self.u.mem_read(self.fb + 128 * (p - 1), 128))

    def key_now(self):
        for t, k, d in self.keys:
            if t <= self.T < t + d:
                return k
        return KEY_INVALID

    def tick(self, ms):
        self.T += ms
        while self.shots and self.T >= self.shots[0][1]:
            label, t = self.shots.pop(0)
            self.taken.append((label, t, [row[:] for row in self.lcd.rows()]))
        if not self.shots and self.T >= self.t_end:
            self.u.emu_stop()

    def audio_sample(self):
        """The ADC value on PA4 at T: the scenario's audio, else receiver hiss."""
        i = int((self.T - self.audio_at) * self.fs / 1000) if self.fs else -1
        return self.audio[i] if 0 <= i < len(self.audio) else 2048 + self.rng.randint(-40, 40)

    def storage_read(self, addr, n):
        """External flash: the scenario's blocks (address -> bytes, or a function
        returning them) over erased flash."""
        out = bytearray(b"\xff" * n)
        for base, data in self.sc.get("storage", {}).items():
            data = data() if callable(data) else data
            lo, hi = max(addr, base), min(addr + n, base + len(data))
            if lo < hi:
                out[lo - addr:hi - addr] = data[lo - base:hi - base]
        return bytes(out)

    def tuned(self):
        """The frequency the app set in REG_38/39 (10 Hz units), else the VFO's."""
        return self.bk.get(0x38, 0) | self.bk.get(0x39, 0) << 16 or self.sc.get("freq", 14450000)

    # ---- hooks ----
    def on_systick(self, u, access, addr, size, value, data):
        """SysTick counts down: apps that time themselves on it (AFSK, FSK
        modems) see it move, and their busy-wait loops advance T."""
        self.tick(SYST_READ_MS)
        u.mem_write(SYST_VAL, struct.pack("<I", SYST_RELOAD - int(self.T * 48000) % (SYST_RELOAD + 1)))

    def on_adc(self, u, access, addr, size, value, data):
        """A conversion is always complete; the data register holds the audio."""
        if addr - ADC_BASE == ADC_SR:
            u.mem_write(addr, struct.pack("<I", ADC_SR_EOC))
        elif addr - ADC_BASE == ADC_DR:
            self.tick(0.005)
            u.mem_write(addr, struct.pack("<I", self.audio_sample()))

    def on_patched(self, u, addr, size, data):
        name = self.patched[addr]
        if name == "FW_ASSETS_Read":
            src, dst, n = self.r(0), self.r(1), self.r(2)
        else:
            dst, src, n = self.r(0), self.r(1), self.r(2)
        o = src - self.fwa_addr
        d = self.fwa[o:o + n] if 0 <= o < len(self.fwa) else b""
        d = d + bytes(n - len(d))
        if name == "FW_ASSETS_ReadStr" and n:
            d = d[:n - 1] + b"\0"
        u.mem_write(dst, d)

    def on_stub(self, u, addr, size, data):
        name = self.stubs.get(addr)
        if name is None:
            return
        sc = self.sc
        if name == "get_key":
            self.tick(0.4)
            self.ret(self.key_now())
        elif name == "delay_ms":
            self.tick(self.r(0))
        elif name == "ticks_ms":
            self.tick(0.01)
            self.ret(int(self.T) // 10 * 10)
        elif name == "cycles_48mhz":
            self.tick(self.cycle_ms)
            self.ret(int(self.T * 48000))
        elif name == "blit_full":
            for p in range(1, 8):
                self.page(p)
            self.tick(7 * BLIT_PAGE_MS)
        elif name == "blit_status":
            self.page(0)
            self.tick(BLIT_PAGE_MS)
        elif name == "blit_line":
            self.page(self.r(0) + 1)
            self.tick(BLIT_PAGE_MS)
        elif name == "blit_page":
            p = self.r(0)
            for q in (range(1, 8) if p == 8 else [p]):
                self.page(q)
            self.tick(BLIT_PAGE_MS * (7 if p == 8 else 1))
        elif name == "lcd_feed":
            n = self.r(0)
            if n == 0:
                self.feed = 0
            else:
                done = self.feed // LCD_PAGE
                self.feed = min(self.feed + n, 8 * LCD_PAGE)
                for p in range(done, self.feed // LCD_PAGE):
                    self.page(p)
                self.tick(n * 0.0107)
            self.ret(self.feed < 8 * LCD_PAGE)
        elif name in ("play_tone", "play_tone_raw"):
            self.tick(self.r(1))
        elif name == "rand32":
            x = self.xs
            x ^= (x << 13) & 0xFFFFFFFF; x ^= x >> 17; x ^= (x << 5) & 0xFFFFFFFF
            self.xs = x
            self.ret(x)
        elif name == "asset_read":
            off, buf, n = self.r(0), self.r(1), self.r(2)
            d = self.assets[off:off + n]
            if d:
                u.mem_write(buf, d)
            self.ret(len(d))
        elif name == "cfg_load":
            buf, n = self.r(0), self.r(1)
            cfg = sc.get("cfg", self.proxy or b"")[:n]
            u.mem_write(buf, cfg + b"\xff" * (n - len(cfg)))
        elif name == "handoff_read":
            buf, mx, frm = self.r(0), self.r(1), self.r(2)
            msg = sc.get("handoff")
            if msg is None:
                self.ret(-1)
            else:
                if mx:
                    u.mem_write(buf, msg[:mx])
                if frm:
                    u.mem_write(frm, sc.get("handoff_from", "").encode()[:16] + b"\0")
                self.ret(len(msg))
        elif name == "rssi_dbm":
            self.ret(int(sc["rssi"](self.T, self.rng, self.tuned())) if "rssi" in sc else -120)
        elif name in ("rx_freq", "tx_freq"):
            self.ret(sc.get("freq", 14450000))
        elif name == "bk_write":
            self.tick(0.03)
            self.bk[self.r(0) & 0xFF] = self.r(1) & 0xFFFF
        elif name == "bk_read":
            self.tick(0.03)
            reg = self.r(0) & 0xFF
            value = self.bk.get(reg, 0)
            if reg == REG_0C and sc.get("squelch") == "audio":
                # squelch open (bit 1) while a carrier burst of the audio is there
                t = self.T - self.audio_at
                if any(a <= t < b for a, b in self.bursts):
                    value |= REG_0C_SQUELCH
            self.ret(value)
        elif name == "af_capture_sample":
            self.tick(0.005)
            self.ret(self.audio_sample())
        elif name == "boot_callsign":
            buf, n = self.r(0), self.r(1)
            if n:
                u.mem_write(buf, sc.get("callsign", "F4HWN").encode()[:n - 1] + b"\0")
        elif name == "sys_storage_read":
            u.mem_write(self.r(1), self.storage_read(self.r(0), self.r(2)))
        elif name in ("sys_stack_free_now", "sys_stack_free_min"):
            self.ret(2048)
        elif name == "serial_ctl":                # a host with the USB-C port open (DTR)
            self.ret(APP_SERIAL_OK | APP_SERIAL_HOST if sc.get("usb_host") and self.r(0) == 0 else 0)
        elif name == "serial_write":
            self.tick(self.r(2) * 0.01)
            self.ret(bool(sc.get("usb_host")))
        elif name == "mr":
            op, index, out = self.r(0), self.r(1), self.r(2)
            chans, lists = sc.get("channels", []), sc.get("lists", [])
            if op == 0 and index < len(chans):        # APP_MR_READ
                freq, label, scan = chans[index]
                if out:
                    u.mem_write(out, struct.pack("<I", freq) + label.encode()[:10].ljust(12, b"\0"))
                self.ret(scan)
            elif op == 1 and 1 <= index <= len(lists):  # APP_MR_LIST_NAME
                label = lists[index - 1].encode()[:4]
                if out:
                    u.mem_write(out, label + b"\0")
                self.ret(len(label))
            else:
                self.ret(-1)
        elif name == "fm_state":
            if not self.r(1):
                u.mem_write(self.r(0), struct.pack("<HHBBB", *sc.get("fm", (1045, 1045, 0, 0, 0))))
        elif name in ("fm_lo", "fm_hi"):
            self.ret(875 if name == "fm_lo" else 1080)
        elif name == "fm_valid":
            self.ret(1)
        elif name in ("led", "backlight_on", "backlight_update", "battery_sample", "set_agc",
                      "set_af", "audio_path", "prepare_tone", "tones_off_rx", "cfg_save",
                      "audio_scope", "tx_set_params", "tx_tone", "tx_mute", "tx_end",
                      "tx_carrier", "tx_prepare", "viewer_update", "af_capture_open",
                      "af_capture_close", "fm_mute", "fm_exit", "fm_commit", "beam_get",
                      "beam_prepare", "fm_enter", "fm_set_freq"):
            self.ret(0)
        else:
            if name not in self.unknown:
                self.unknown.add(name)
                print(f"  note: {name}() stubbed, returns 0")
            self.ret(0)

    def run(self):
        u = self.u
        u.reg_write(UC_ARM_REG_SP, self.fw.get("_estack", RAM + 0x4000))
        u.reg_write(UC_ARM_REG_R0, API)
        u.reg_write(UC_ARM_REG_LR, MAGIC | 1)
        try:
            u.emu_start(self.app["app_main"] | 1, MAGIC, timeout=120_000_000)
        except Exception as e:
            pc = u.reg_read(UC_ARM_REG_PC)
            print(f"  emulation stopped at T={self.T:.0f} ms, pc={pc:#x}: {e}")
        self.returned = u.reg_read(UC_ARM_REG_PC) & ~1 == MAGIC
        for label, t in self.shots:            # the app returned before these
            self.taken.append((label, t, self.lcd.rows()))
        return self


