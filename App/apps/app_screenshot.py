def test_module(app, name):
    """App/apps/<app>/test/<name>.py, the model the app is validated against,
    under a name of its own (several apps have a model_rx.py)."""
    d = os.path.join(HERE, app, "test")
    sys.path.insert(0, d)
    try:
        spec = importlib.util.spec_from_file_location(f"{app}_{name}", os.path.join(d, name + ".py"))
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    finally:
        sys.path.remove(d)
    return module


def aprs_audio():
    """Three stations on 144.800: a mobile, a digipeater, a fixed station
    relayed by it."""
    ax25, rx = test_module("aprsrx", "ax25"), test_module("aprsrx", "model_rx")
    frames = [ax25.build("F4ABC-9", path=["WIDE1-1"], info="!4851.20N/00221.30E>Mobile UV-K5"),
              ax25.build("F1ZZZ-10", path=["WIDE2-1"], info="!4847.04N/00206.09E#Digi"),
              ax25.build("F5XYZ", path=["F1ZZZ-10*", "WIDE2-1"], info="=4855.12N/00218.40E-QRV 145.500")]
    adc = []
    for k, frame in enumerate(frames):
        adc += rx.channel(rx.sine_wave(frame), "raw", 300, 0, 0, k + 1, gap_ms=300)
    return adc, rx.FS_ADC


def aprs_frame_audio():
    """An APRS frame, then its digipeated copy 450 ms later, each on its own
    carrier: they cross AF Spectro's sonogram as two 1200 / 2200 Hz blocks.
    The third item lists the bursts (ms from the audio start): the squelch is
    open during them only."""
    ax25, rx = test_module("aprsrx", "ax25"), test_module("aprsrx", "model_rx")
    info = "!4850.90N/00216.25E-UV-K5 APRS, F4HWN firmware"
    adc, bursts = [], []
    for k, path in enumerate((["WIDE1-1"], ["F1ZZZ-10*", "WIDE1*"])):
        if k:
            adc += [rx.BIAS] * int(0.45 * rx.FS_ADC)
        burst = rx.channel(rx.sine_wave(ax25.build("F4HWN-7", path=path, info=info)), "raw", 300, 0, 0, k + 1,
                           gap_ms=0)
        bursts.append((len(adc) * 1000 / rx.FS_ADC, (len(adc) + len(burst)) * 1000 / rx.FS_ADC))
        adc += burst
    return adc, rx.FS_ADC, bursts


