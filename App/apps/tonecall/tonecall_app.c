/*
 * ToneCall - overlay app: sends a sequential tone call (ZVEI-1, ZVEI-2, CCIR-1,
 * CCIR-2) chosen among the user's presets, on demand, on the current channel.
 *
 * The TC_PRESET_COUNT presets and the last one used are packed into the app's
 * 16-byte config area (tonecall_seq.h), edited here. Nothing is built in.
 *
 * A call keys up with the channel's TX settings (CTCSS/DCS included), leaves
 * TC_PRELOAD_MS of carrier, sends the tones back to back and unkeys, through
 * the existing API only. The app then stays in RX with the speaker following
 * the squelch, so the station's acknowledgement is heard; EXIT returns to the
 * channel, where the conversation goes on with the PTT (no code is ever sent
 * with the PTT).
 *
 * Keys: UP/DOWN (UV-K1: LEFT/RIGHT) select · MENU or PTT send · F edit ·
 *       EXIT quit (from the listen screen: MENU/PTT sends again, UP/DOWN
 *       back to the list).
 * Editor: 0-9 add a digit · F delete · * next type · MENU keep · EXIT discard.
 */

#include <stdint.h>
#include <stdbool.h>
#include "../app_api.h"
#include "tonecall_seq.h"
#include "tonecall_assets.h"   /* generated by gen_assets.py */

#ifndef APP_VERSION
#define APP_VERSION "dev"
#endif

#define LOOP_MS        10u
#define TC_PRELOAD_MS  300u    /* carrier (+ CTCSS) before the first tone */

/* BK4819/BK4829 registers, values as the resident tone path writes them. */
#define REG_0C         0x0Cu   /* bit 1: squelch open */
#define REG_30         0x30u
#define REG_70         0x70u
#define REG_30_TX_LINK 0xC3FAu /* BK4819_EnableTXLink                      */
#define REG_30_IDLE    0xC1FEu /* as BK4819_PlaySingleTone leaves it       */
#define REG_70_TONE1   0xC200u /* TONE1 on, tuning gain 66 (as 1750 Hz)    */

enum { SCREEN_LIST = 0, SCREEN_LISTEN, SCREEN_EDIT };

static struct {
    const app_api_t *A;
    uint8_t sel, screen, held, type, codeLen;
    bool running, dirty, changed, sentOk, sqlOpen;
    char code[TC_MAX_DIGITS + 1u];
    uint32_t preset[TC_PRESET_COUNT];
} g;
#define A (g.A)

/* ---- tiny formatting (no division linked) ---- */
static uint8_t slen(const char *s){ uint8_t n=0; while(s[n]) n++; return n; }
static char *put(char *o, const char *s){ while(*s) *o++=*s++; return o; }
/* v in decimal, at least min (1-9) digits (zero padded), at most 9: no NUL. */
static char *putu(char *o, uint32_t v, uint8_t min){
    bool lead=true;
    for(uint8_t i=TC_POW10_COUNT;i--;){
        const uint32_t place=tcPow10[i];
        uint8_t d=0;
        while(v>=place&&d<9u){ v-=place; d++; }
        if(d||i<min) lead=false;
        if(!lead) *o++=(char)('0'+d);
    }
    return o;
}

/* ---- presets ---- */
/* Load preset i into g.code / g.type / g.codeLen; false if it is empty. */
static bool loadPreset(uint8_t i){
    g.codeLen=TC_UnpackPreset(g.preset[i],&g.type,g.code);
    return g.codeLen!=0;
}

/* ---- the channel's TX tone ---- */
/* "CT123.0", "D023N" or "D023I" from the TX VFO (beam_get, Labs builds), in
 * s; false when the channel has none or the service is absent. */
static bool txTone(char *s){
    app_beam_channel_t ch;
    if(!A->beam_get) return false;
    A->beam_get(&ch);
    /* beam_get exports the stored RX/TX sides; reverse makes the stored RX
     * side the effective TX side used by RADIO_SetTxParameters. */
    const uint8_t type=ch.frequency_reverse?ch.rx_codetype:ch.tx_codetype;
    const uint8_t code=ch.frequency_reverse?ch.rx_code:ch.tx_code;
    char *o=s;
    if(type==1u && code<CTCSS_COUNT){                          /* CTCSS, Hz x 10 */
        uint16_t v;
        A->asset_read((uint16_t)(CTCSS+code*2u),&v,2u);
        *o++='C'; *o++='T';
        char *e=putu(o,v,2u);                 /* "x.y" at least */
        e[1]='\0'; e[0]=e[-1]; e[-1]='.';
        return true;
    }
    if((type==2u||type==3u) && code<DCS_COUNT){               /* DCS N / I */
        uint8_t low;
        A->asset_read((uint16_t)(DCS_LOW+code),&low,1u);
        const uint16_t v=(uint16_t)(low|(code>=64u?0x100u:0u));
        *o++='D';
        *o++=(char)('0'+((v>>6)&7u)); *o++=(char)('0'+((v>>3)&7u)); *o++=(char)('0'+(v&7u));
        *o++=type==2u?'N':'I'; *o='\0';
        return true;
    }
    return false;
}

/* ---- drawing ---- */
static void invertLine(uint8_t line){ for(uint8_t x=0;x<128u;x++) A->fb[line][x]^=0xFFu; }

/* "1 ZVEI-1" left, the code right: the row of preset i on a frame line. */
static void drawRow(uint8_t i, uint8_t line){
    char s[10];
    const bool used=loadPreset(i);
    char *o=s; *o++=(char)('1'+i); *o++=' ';
    o=put(o,used?tcTypeNames[g.type]:"EMPTY"); *o='\0';
    A->print_normal(s,1u,0u,line);
    if(used) A->print_normal(g.code,(uint8_t)(127u-g.codeLen*7u),0u,line);
}

static void chrome(const char *title){
    char s[16];
    A->display_clear();
    A->status_clear();
    A->print_inverse(title,2u,0u,true,true,(uint8_t)(2u+slen(title)*4u));
    A->print_tiny(APP_VERSION,(uint8_t)(6u+slen(title)*4u),1u,true,false);
    A->draw_battery();
    /* the TX frequency (10 Hz units) as MHz with 5 decimals */
    { char *e=putu(s,A->tx_freq(),6u);     /* 5 decimals + 1 */
      e[1]='\0';
      for(uint8_t k=0;k<5u;k++,e--) e[0]=e[-1];
      e[0]='.'; }
    A->print_normal(s,1u,0u,0u);
    /* the channel's TX tone, when there is one, right-aligned */
    if(txTone(s)) A->print_normal(s,(uint8_t)(127u-slen(s)*7u),0u,0u);
}

static void drawList(void){
    chrome("TONECALL");
    for(uint8_t i=0;i<TC_PRESET_COUNT;i++){
        drawRow(i,(uint8_t)(1u+i));
        if(i==g.sel) invertLine((uint8_t)(1u+i));
    }
    A->print_tiny("M/PTT SEND  F EDIT",1u,50u,false,false);
}

/* The draft of the preset being edited: g.type / g.code. */
static void drawEdit(void){
    char s[10];
    A->display_clear(); A->status_clear();
    A->print_inverse("TC EDIT",2u,0u,true,true,30u);
    A->print_tiny(APP_VERSION,34u,1u,true,false);
    A->draw_battery();
    { char *e=put(s,"PRESET 1"); e[-1]=(char)('1'+g.sel); *e='\0'; }
    A->print_normal(s,0u,127u,0u);
    A->print_normal("TYPE",2u,0u,2u);
    A->print_normal(tcTypeNames[g.type],44u,0u,2u);
    A->print_normal("CODE",2u,0u,3u);
    A->print_normal(g.codeLen?g.code:"EMPTY",44u,0u,3u);
    A->print_tiny("0-9 CODE  F DEL  * TYPE",1u,42u,false,false);
    A->print_tiny("M KEEP  EXIT CANCEL",1u,50u,false,false);
}

static void drawListen(void){
    chrome("TONECALL");
    loadPreset(g.sel);
    A->print_string(g.code,0u,127u,1u,8u);
    A->print_normal(g.sentOk?(g.sqlOpen?"RX":"LISTENING"):"TX OFF",0u,127u,4u);
    A->print_tiny(tcTypeNames[g.type],1u,50u,false,false);
    A->print_tiny(g.code,(uint8_t)(127u-slen(g.code)*4u),50u,false,false);
}

static void draw(void){
    if(g.screen==SCREEN_LISTEN) drawListen();
    else if(g.screen==SCREEN_EDIT) drawEdit();
    else drawList();
    A->blit_status(); A->blit_full();
}

/* ---- the call ---- */
/* Key up, TC_PRELOAD_MS of carrier, the tones back to back, unkey: the same
 * register sequence as the resident tone path (BK4819_PlaySingleTone), with
 * the channel's CTCSS/DCS left on by tx_set_params. */
static bool sendCall(void){
    uint16_t tones[TC_MAX_DIGITS];
    if(!loadPreset(g.sel)) return false;
    const uint8_t n=TC_BuildTones(g.type,g.code,tones);
    const uint16_t ms=TC_ToneMs(g.type);
    if(!n||A->tx_state()!=0) return false;

    A->tx_set_params();                 /* carrier + PA, channel CTCSS/DCS   */
    A->tx_mute(true);                   /* microphone path muted             */
    A->set_af(APP_AF_MUTE);
    A->bk_write(REG_70,REG_70_TONE1);
    A->bk_write(REG_30,REG_30_TX_LINK);
    A->led(true);
    A->delay_ms(TC_PRELOAD_MS);
    for(uint8_t k=0;k<n;k++) A->play_tone_raw(tones[k],ms);   /* unmute, tone, mute */
    A->bk_write(REG_70,0u);
    A->bk_write(REG_30,REG_30_IDLE);
    A->tx_mute(true);
    A->tx_end();                        /* PA off + RX registers restored     */
    A->led(false);
    return true;
}

static void startCall(void){
    g.sentOk=sendCall();
    g.screen=SCREEN_LISTEN;
    g.sqlOpen=false;
    if(g.sentOk) A->set_af(APP_AF_FM);
    g.dirty=true;
}

static void leaveListen(void){
    A->audio_path(false);
    A->set_af(APP_AF_MUTE);
    g.screen=SCREEN_LIST;
}

/* ---- keys ---- */
static void listKey(uint8_t key){
    const int8_t d=A->nav_dir(key);
    if(d>0) g.sel=(uint8_t)(g.sel+1u<TC_PRESET_COUNT?g.sel+1u:0u);
    else if(d<0) g.sel=(uint8_t)(g.sel?g.sel-1u:TC_PRESET_COUNT-1u);
    else if(key==APP_KEY_MENU||key==APP_KEY_PTT){ if(g.preset[g.sel]) startCall(); }
    else if(key==APP_KEY_F){ loadPreset(g.sel); g.screen=SCREEN_EDIT; }
    else if(key==APP_KEY_EXIT) g.running=false;
}

static void editKey(uint8_t key){
    if(key<=APP_KEY_9){
        if(g.codeLen<TC_MAX_DIGITS){ g.code[g.codeLen++]=(char)('0'+key); g.code[g.codeLen]='\0'; }
    }
    else if(key==APP_KEY_F){ if(g.codeLen) g.code[--g.codeLen]='\0'; }
    else if(key==APP_KEY_STAR) g.type=(uint8_t)(g.type+1u<TC_TYPE_COUNT?g.type+1u:0u);
    else if(key==APP_KEY_MENU){
        const uint32_t v=TC_PackPreset(g.type,g.code);   /* empty code: empty preset */
        if(v!=g.preset[g.sel]){ g.preset[g.sel]=v; g.changed=true; }
        g.screen=SCREEN_LIST;
    }
    else if(key==APP_KEY_EXIT) g.screen=SCREEN_LIST;   /* the preset is untouched */
}

static void listenKey(uint8_t key){
    if(key==APP_KEY_MENU||key==APP_KEY_PTT){ startCall(); return; }
    leaveListen();
    if(key==APP_KEY_EXIT) g.running=false;
}

__attribute__((section(".text.entry"),used))
void app_main(const app_api_t *api){
    uint32_t cfg[TC_PRESET_COUNT];
    uint8_t saved;
    A=api;
    g.held=APP_KEY_INVALID;
    api->cfg_load((uint8_t *)cfg,TC_CFG_LEN);
    TC_CfgUnpack(cfg,g.preset,&g.sel);
    saved=g.sel;
    g.running=true; g.dirty=true;
    api->backlight_on();

    while(g.running){
        if(g.screen==SCREEN_LISTEN && g.sentOk){
            /* speaker on while the squelch is open: the acknowledgement is heard */
            const bool open=(A->bk_read(REG_0C)&2u)!=0;
            A->audio_path(open);
            if(open!=g.sqlOpen){ g.sqlOpen=open; g.dirty=true; }
        }
        if(g.dirty){ g.dirty=false; draw(); }
        const uint8_t key=api->get_key();
        if(key==APP_KEY_SAVER||key==APP_KEY_WAKE){ g.held=APP_KEY_INVALID; g.dirty=true; }
        else if(key!=g.held){
            g.held=key;
            if(key!=APP_KEY_INVALID){
                api->backlight_on();
                if(g.screen==SCREEN_LISTEN) listenKey(key);
                else if(g.screen==SCREEN_EDIT) editKey(key);
                else listKey(key);
                g.dirty=true;
            }
        }
        api->battery_sample(); api->delay_ms(LOOP_MS); api->backlight_update();
    }

    if(g.screen==SCREEN_LISTEN) leaveListen();
    if(g.changed||g.sel!=saved){                       /* flash written only on change */
        TC_CfgPack(cfg,g.preset,g.sel);
        api->cfg_save((const uint8_t *)cfg,TC_CFG_LEN);
    }
}
