/*
 * Resistor - colour-code calculator overlay, after the Flipper Zero
 * "resistors" app by Lewis Westbury (instantiator, MIT licence).
 *
 * 3, 4, 5 or 6 band resistors (IEC 60062): the value with its SI prefix in
 * the small bold font, the tolerance (and the temperature coefficient with 6
 * bands) in the 3x5 font, and the resistor itself. Under each band: its
 * three-letter colour code (a capsule for the selected band) and, for the digits
 * and the multiplier, what it contributes to the value.
 *
 * Keys: the arrows select the band, STAR steps its colour forward and F then
 * STAR back (the colours that band accepts only), 0-9 set it to that colour
 * code and select the next band, MENU cycles 3 -> 4 -> 5 -> 6 bands (keeping
 * the value from 4 to 5 bands and, when the third digit is 0, from 6 to 3),
 * EXIT quits. The last resistor is kept for the next launch.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "resistor_assets.h"   /* generated by gen_assets.py */

#define W           128u
#define TICK_MS      40u
#define REFRESH_MS 1000u        /* battery refresh while nothing changes */

/* Frame-buffer layout (y in frame-buffer pixels, under the status line). */
#define TOL_Y         8u        /* tolerance / tempco, 3x5 font, over the body art */
#define CODE_LINE     5u        /* colour codes, 3x5 font (capsule line) */
#define VALUE_Y      49u        /* digit / multiplier under each code */
#define BANDS_X      40u        /* "4 BANDS" in the status line */
#define FN_X         80u        /* "F" capsule while F is armed */

_Static_assert((TOL_Y & 7u) + 5u <= 8u, "the plus-minus sign must fit one page");

/* All the state in one struct (one literal per function). type and roles stay
 * first and adjacent: they are the saved config, as DEFAULTS lays them out. */
struct globals {
    uint8_t type;               /* band count, 3..6 */
    uint8_t roles[ROLES];       /* colour of each band role: D0 D1 D2 MULT TOL TC */
    uint8_t sel, previousKey;
    int8_t starDir;             /* colour step of the STAR press being held */
    bool running, saverActive, dirty, fn;
    uint16_t repeatMs;
    uint32_t drawnAt;
    const app_api_t *api;
};
static struct globals g;
#define A (g.api)
#define CFG_LEN (1u + ROLES)

_Static_assert(offsetof(struct globals, roles) == 1u, "config bytes must be contiguous");

/* -------------------------------------------------------------------------- */
/*  Colour-code logic                                                         */
/* -------------------------------------------------------------------------- */

/* Multiplier colour <-> power of ten: black..white are 0..9, gold -1 and
 * silver -2. The same mapping works both ways. */
static int32_t flip(int32_t x)
{
    return (uint32_t)x < 10u ? x : 9 - x;
}

/* The colours a band role accepts, one bit per colour. */
static uint32_t valid_colours(uint32_t role)
{
    uint16_t m;
    A->asset_read(MASKS + role * 2u, &m, sizeof(m));
    return m;
}

/* Role (or left x) of each band of the current band count. */
static void layout(uint16_t table, uint8_t *out)
{
    A->asset_read(table + (g.type - 3u) * ROLES, out, ROLES);
}

static uint32_t role_of_sel(void)
{
    uint8_t roles[ROLES];
    layout(LAYOUT, roles);
    return roles[g.sel];
}

/* The value with an SI prefix and three significant digits at most, then a
 * blank cell for the ohm sign: "4.7 k ", "0.47  ", "100 G ". Returns its
 * length. */
static uint32_t value_text(char *s)
{
    char d[3];
    int32_t n = 0;
    uint32_t k = 0;                                  /* prefix: none, k, M, G */
    const uint32_t count = g.type >= 5u ? 3u : 2u;
    for (uint32_t i = 0; i < count; i++)
        if (n || g.roles[i])                         /* no leading zero */
            d[n++] = (char)('0' + g.roles[i]);

    char *o = s;
    if (!n) {
        *o++ = '0';
    } else {
        int32_t p = n + flip(g.roles[ROLE_MULT]);    /* digits before the point */
        while (k < 3u && p > 3) {
            p -= 3;
            k++;
        }
        const bool point = p < n;
        if (p <= 0) {                                /* below one: "0.0..." */
            *o++ = '0';
            *o++ = '.';
            while (p++ < 0)
                *o++ = '0';
            for (int32_t i = 0; i < n; i++)
                *o++ = d[i];
        } else {                                     /* point inside, or zero padding */
            for (int32_t i = 0; i < n || i < p; i++) {
                if (i == p)
                    *o++ = '.';
                *o++ = i < n ? d[i] : '0';
            }
        }
        if (point) {                                 /* drop the trailing zeros */
            while (o[-1] == '0')
                o--;
            if (o[-1] == '.')
                o--;
        }
    }
    *o++ = ' ';
    if (k)
        *o++ = (char)("kMG"[k - 1u]);
    *o++ = ' ';
    *o = '\0';
    return (uint32_t)(o - s);
}

/* MENU: 3 -> 4 -> 5 -> 6 -> 3 bands. From two to three digits the value is
 * kept as d0 d1 0 x 10^(e-1), and back from three to two when the third digit
 * is 0 (both within the multiplier range). */
static void cycle_bands(void)
{
    const int32_t e = flip(g.roles[ROLE_MULT]);
    if (g.type == 4u && e > -2) {
        g.roles[ROLE_D2] = 0;
        g.roles[ROLE_MULT] = (uint8_t)flip(e - 1);
    } else if (g.type == 6u && g.roles[ROLE_D2] == 0u && e < 9) {
        g.roles[ROLE_MULT] = (uint8_t)flip(e + 1);
    }
    g.type = g.type == 6u ? 3u : (uint8_t)(g.type + 1u);
    if (g.sel >= g.type)
        g.sel = (uint8_t)(g.type - 1u);
}

/* Select the band dir (+1 / -1) steps away, wrapping around. */
static void move_band(int32_t dir)
{
    if (dir > 0)
        g.sel = g.sel + 1u >= g.type ? 0u : (uint8_t)(g.sel + 1u);
    else
        g.sel = (uint8_t)((g.sel ? g.sel : g.type) - 1u);
}

/* The next (dir +1) or previous (-1) colour the selected band accepts. */
static void step_colour(int32_t dir)
{
    const uint32_t role = role_of_sel();
    const uint32_t valid = valid_colours(role);
    uint32_t c = g.roles[role];
    do {
        if (dir > 0)
            c = c + 1u == COLOURS ? 0u : c + 1u;
        else
            c = c ? c - 1u : COLOURS - 1u;
    } while (!((valid >> c) & 1u));
    g.roles[role] = (uint8_t)c;
}

/* 0-9: the colour of that code, when the selected band accepts it, then the
 * next band. */
static void enter_digit(uint32_t digit)
{
    const uint32_t role = role_of_sel();
    if ((valid_colours(role) >> digit) & 1u) {
        g.roles[role] = (uint8_t)digit;
        move_band(1);
    }
}

/* -------------------------------------------------------------------------- */
/*  Rendering                                                                 */
/* -------------------------------------------------------------------------- */

/* Read an asset text at o; returns its end. o needs TEXT_MAX bytes free. */
static char *cat(char *o, uint16_t off)
{
    A->asset_read(off, o, TEXT_MAX);
    while (*o)
        o++;
    return o;
}

/* 3x5 text centred on column cx of frame-buffer row y. */
static void tiny_centred(char *s, char *end, uint32_t cx, uint32_t y)
{
    const uint32_t width = (uint32_t)(end - s) * 4u - 1u;
    A->print_tiny(s, (uint8_t)(cx - (width >> 1)), (uint8_t)y, false, true);
}

static void render(void)
{
    char s[24];
    uint8_t roles[ROLES], xs[ROLES];
    char *o;

    A->display_clear();
    A->status_clear();
    cat(s, T_TITLE);
    A->print_inverse(s, 2, 0, true, true, (uint8_t)(2u + (T_TITLE_LEN - 1u) * 4u));
    s[0] = (char)('0' + g.type);
    cat(s + 1, T_BANDS);
    A->print_tiny(s, BANDS_X, 1, true, true);
    if (g.fn) {
        cat(s, T_F);
        A->print_inverse(s, FN_X, 0, true, true, FN_X + 4u);
    }
    A->draw_battery();

    /* The value in the small bold font, centred as print_bold centres it,
       the ohm sign drawn into its trailing blank cell. */
    const uint32_t len = value_text(s);
    A->print_bold(s, 0, W - 1u, 0);
    const uint32_t ox = ((W - len * 7u) >> 1) + (len - 1u) * 7u + 1u;
    uint8_t sign[OHM_LEN];
    A->asset_read(OHM, sign, OHM_LEN);
    for (uint32_t c = 0; c < OHM_LEN; c++)
        A->fb[0][ox + c] |= sign[c];

    /* The body art first: its top page is shared with the tolerance line. */
    A->asset_read(ART_BODY, A->fb[BODY_LINE], ART_BODY_LEN);

    /* Tolerance (20 % without a tolerance band) and, with 6 bands, the
       temperature coefficient, in the 3x5 font; the plus-minus sign is drawn
       into the leading blank. */
    const uint32_t tol = g.type > 3u ? g.roles[ROLE_TOL] : NO_TOL;
    s[0] = ' ';
    o = cat(s + 1, T_TOLV + tol * T_TOLV_STRIDE);
    if (g.type == 6u) {
        *o++ = ' ';
        *o++ = ' ';
        o = cat(cat(o, T_TCV + g.roles[ROLE_TC] * T_TCV_STRIDE), T_PPM);
    }
    const uint32_t tx = (W >> 1) - (((uint32_t)(o - s) * 4u - 1u) >> 1);
    A->print_tiny(s, (uint8_t)tx, TOL_Y, false, true);
    A->asset_read(PLUS_MINUS, sign, PLUS_MINUS_LEN);
    for (uint32_t c = 0; c < PLUS_MINUS_LEN; c++)
        A->fb[TOL_Y >> 3][tx + c] |= (uint8_t)(sign[c] << (TOL_Y & 7u));

    /* Each band: its area cleared with an edge on both sides, or filled
       when selected; its colour code under it (a capsule when selected), and
       under that, for the digits and the multiplier, what it contributes. */
    layout(LAYOUT, roles);
    layout(LAYOUT_X, xs);
    for (uint32_t i = 0; i < g.type; i++) {
        const uint32_t bx = xs[i];
        const uint32_t role = roles[i];
        const uint32_t colour = g.roles[role];
        const bool selected = i == g.sel;
        for (uint32_t p = 0; p < BODY_PAGES; p++) {
            uint8_t fill[BAND_W];
            uint8_t *col = &A->fb[BODY_LINE + p][bx];
            A->asset_read(ART_FILL + p * W + bx, fill, BAND_W);
            for (uint32_t c = 0; c < BAND_W; c++) {
                if (selected)
                    col[c] |= fill[c];
                else
                    col[c] = (uint8_t)((col[c] & ~fill[c]) |
                                       ((c == 0u || c == BAND_W - 1u) ? fill[c] : 0u));
            }
        }

        const uint32_t cx = bx + BAND_W / 2u;
        const uint32_t lx = cx - ((CODE_CHARS * 4u - 1u) >> 1);
        A->asset_read(T_COLOUR + colour * T_COLOUR_STRIDE, s, T_COLOUR_STRIDE);
        if (selected)
            A->print_inverse(s, (uint8_t)lx, CODE_LINE, false, true, (uint8_t)(lx + CODE_CHARS * 4u));
        else
            A->print_tiny(s, (uint8_t)lx, CODE_LINE * 8u + 1u, false, true);

        if (role < ROLE_MULT) {
            s[0] = (char)('0' + colour);
            s[1] = '\0';        /* s still holds the colour code */
            tiny_centred(s, s + 1, cx, VALUE_Y);
        } else if (role == ROLE_MULT) {
            tiny_centred(s, cat(s, T_MULT + colour * T_MULT_STRIDE), cx, VALUE_Y);
        }
    }
}

/* -------------------------------------------------------------------------- */
/*  Input, screensaver handling and the main loop                             */
/* -------------------------------------------------------------------------- */

static void key_action(uint8_t key, bool repeat)
{
    const int8_t dir = A->nav_dir(key);

    g.dirty = true;
    if (dir) {                  /* arrows: the band, auto-repeating */
        g.fn = false;
        move_band(dir);
        return;
    }
    if (key == APP_KEY_STAR) {  /* STAR forward, F STAR back, auto-repeating */
        if (!repeat) {
            g.starDir = g.fn ? -1 : 1;
            g.fn = false;
        }
        step_colour(g.starDir);
        return;
    }
    if (repeat)
        return;
    if (key == APP_KEY_F) {     /* arm (or disarm) F for the next key */
        g.fn = !g.fn;
        return;
    }
    g.fn = false;
    if (key <= APP_KEY_9)
        enter_digit(key);
    else if (key == APP_KEY_MENU)
        cycle_bands();
    else if (key == APP_KEY_EXIT)
        g.running = false;
}

static void poll_key(void)
{
    uint8_t key = A->get_key();
    if (key == APP_KEY_SAVER) {
        g.saverActive = true;
        g.previousKey = APP_KEY_INVALID;
        g.repeatMs = 0;
        return;
    }
    if (key == APP_KEY_WAKE || key == APP_KEY_PTT) {
        g.saverActive = false;
        g.dirty = true;
        key = APP_KEY_INVALID;
    }
    if (key == APP_KEY_INVALID) {
        g.previousKey = key;
        g.repeatMs = 0;
        return;
    }
    if (key != g.previousKey) {
        A->backlight_on();
        key_action(key, false);
        g.repeatMs = 260u;
    } else if (g.repeatMs > TICK_MS) {
        g.repeatMs -= TICK_MS;
    } else {
        key_action(key, true);
        g.repeatMs = 80u;
    }
    g.previousKey = key;
}

/* The saved resistor, or the defaults when it is missing (erased flash) or
 * not a valid one. */
static void load_config(void)
{
    bool ok;
    A->cfg_load(&g.type, CFG_LEN);
    ok = g.type >= 3u && g.type <= 6u;
    for (uint32_t r = 0; ok && r < ROLES; r++)
        ok = g.roles[r] < COLOURS && ((valid_colours(r) >> g.roles[r]) & 1u);
    if (!ok)
        A->asset_read(DEFAULTS, &g.type, CFG_LEN);
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api)
{
    A = api;
    load_config();
    g.previousKey = A->get_key();    /* a key still held from the launcher is ignored */
    g.running = true;
    g.dirty = true;
    A->backlight_on();

    while (g.running) {
        poll_key();
        if (!g.running)
            break;

        const uint32_t now = A->ticks_ms();
        if (!g.saverActive && (g.dirty || now - g.drawnAt >= REFRESH_MS)) {
            render();
            A->blit_status();
            A->blit_full();
            g.dirty = false;
            g.drawnAt = now;
        }
        A->battery_sample();
        A->backlight_update();
        A->delay_ms(TICK_MS);
    }

    A->cfg_save(&g.type, CFG_LEN);   /* staged: committed after the app returns */
}
