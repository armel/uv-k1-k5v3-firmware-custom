/*
 * POCSAG RX - receives POCSAG pager transmissions at 1200 bauds (as the
 * amateur DAPNET network sends them) and keeps the last ten pages, shown one
 * at a time: address (RIC), text, function. Tune the VFO (FM, wide; 439.9875
 * MHz for DAPNET, or 433.650 MHz for the Flipper Zero bench files of
 * test/flipper_pocsag.py), then launch.
 *
 * POCSAG keys the carrier frequency with the bits themselves (direct FSK,
 * NRZ): the BK4829's own FSK modem receives that, in its "FSK 1.2K" mode, and
 * it demodulates since 1.0 (up to 0.9 the app sampled the RX audio and sliced
 * it in software). The chip keeps the bit clock, finds the sync codeword
 * 7CD215D8 (its 4-byte sync word, after a 16-byte preamble) and puts the bits
 * that follow in its FIFO, 16 a word, the first byte off the air in the low
 * half. Its frame is 2040 bytes: 30 batches, each with the sync codeword of
 * the next one, which the modem reads as data. The app reads four words at
 * each FIFO almost-full interrupt, checks that sync codeword after each batch
 * (in either polarity: it tells which one the transmission is in, the modem
 * takes both), corrects one wrong bit per codeword and assembles the pages.
 * No audio is sampled, so the RX audio path (its high-pass, de-emphasis) is
 * not in the way. The set-up is Ferrite's (Radtel RT-950, also a BK4829),
 * measured on a UV-K1 (README, "Hardware decoding").
 * A codeword that cannot be corrected does not end a page: its characters are
 * marked '?'. Three in a row do. A new page blinks the green LED twice.
 *
 * Keys (UV-K5 and UV-K1): UP/DOWN scroll the text a row when it overflows;
 *   pressed again at either end: the newer / older page · * normal view /
 *   compact view (saved) · 1 speaker on/off (saved, off by default; not gated
 *   by the squelch: the receiver's hiss is heard) · 2 clear · 3 bottom line:
 *   level and age of the page / the modem's counters · 4 keep the pages
 *   without text (saved, off by default) · EXIT quit.
 * The loader re-runs RADIO_SetupRegisters on exit; the app turns the modem
 * off before it returns.
 */

