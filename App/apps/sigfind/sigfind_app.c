/*
 * Sig Finder (RX only), the Signal Finder - overlay app forked from FoxHunt.
 * Direction finding of any carrier (a 121.5 / 243 MHz homing beacon, a fox,
 * an interferer) with a directional antenna: tune the VFO (AM, FM or USB)
 * first, then launch. Feedback is RELATIVE to a peak, not absolute dBm, so it
 * keeps working when the signal gets strong: the closer the reading is to the peak, the
 * faster and higher the beeps; within ONPEAK_Q of it, a fast high "on peak" chirp.
 *
 *   FOLLOW (default): the peak falls back slowly (0.5/1/2/4 dB/s), so the app always
 *                     answers "is this the best direction of the last few seconds".
 *   SWEEP:            the peak never decays. MENU starts a new sweep: turn 360 deg,
 *                     then turn back until the feedback says you are on the maximum.
 *
 * Direction finding works on any modulation (RSSI is taken before demodulation and
 * the app never retunes). Listening follows the firmware (radio.c): AM and FM both
 * use the FM AF output, the VFO having already enabled the AM demodulator in REG_31;
 * USB uses the baseband output. The USB listen mode is picked at launch when the VFO
 * had it set (REG_47 is muted while the squelch is closed, so it can also be chosen
 * by hand).
 *
 * Swept-tone detector (sweep.c): while the AF output is on (audio off or
 * listen), the RX audio is sampled on PA4 at 9.6 kHz during each tick's 50 ms
 * pause and its frequency tracked. A homer's downward sweep (1600..300 Hz,
 * 2..4 Hz) shows "ELT" in the status bar and its range and rate on the line
 * above the graph; otherwise that line shows the audio frequency, amplitude
 * and score. PA4 receives the AF before the speaker amplifier, so audio off
 * keeps the speaker quiet. In beep mode the AF is muted between beeps: no
 * detection there.
 *
 * An auto attenuator steps the front end up before the RSSI saturates (and back
 * down when weak, FOLLOW only) and re-bases the peak by the measured offset.
 *
 * Keys (identical on UV-K5 and UV-K1; UP/DOWN go through nav_dir):
 *   1 mode FOLLOW/SWEEP · 2 audio off/beep/listen/listen USB · 3 attenuator step
 *   (manual) · 4 auto attenuator on/off · 5 decay rate · 6 backlight held on/off
 *   (saved) · UP/DOWN attenuator (manual) · MENU reset peak / new sweep
 *   F reverses 2, 3 and 5 · long F keypad lock · EXIT quit.
 *
 * Size: texts, icons, the attenuator ladder and the powers of ten are read-only
 * assets (gen_assets.py), the state is one struct, the history lives on
 * app_main's stack, and the only division (the sweep rate) goes through the
 * resident uidivmod. Needs API level 2 (v6.1.0+). The loader re-runs
 * RADIO_SetupRegisters on exit; the app restores the ADC, PA4, the DAC and its
 * clock itself.
 */

