/*
 * AF Scope - an oscilloscope and a tuner for the demodulated RX audio, not
 * for RF: the BK4829 AF output, sampled on PA4 (the voice DAC pin) as APRS RX
 * does. The time half of an instrument whose other half is AF Spectro
 * (spectrum, sonogram, twist): MENU on the last view hands off to it.
 *   SCOPE  the trace over the screen, triggered on a rising or falling zero
 *          crossing, 0.8 to 13 ms per division (peak detect when a pixel
 *          holds several samples), gain AUTO / x1 / x2 / x4 / x8 / x16,
 *          persistence;
 *          the frequency counter (one frequency, or the two of an FSK), pp,
 *          DC, the RF frequency;
 *   TUNE   the frequency of a steady tone in big digits, its stability, a
 *          needle against the nearest known tone (1750 Hz call tone, DTMF,
 *          Bell 202, SSTV, CW...), the period folded over two cycles.
 * It names nothing it hears: the tone names are labels of the needle.
 *
 * Measurement (test/model.py is the reference, keep the two in step): a
 * block of samples is taken with nothing else running but, while the speaker
 * is on, the LCD bytes sent with the samples (lcd_feed). Its rising zero
 * crossings (hysteresis pp/8, interpolated to 1/256 sample) give the mean
 * period; a second pass sums the periods more than 1/8 longer and shorter
 * than it. With fewer than 1/8 of them the block is a steady tone, one
 * frequency; else the two are shown (FSK: 1200/2200). TUNE takes 640 samples
 * at 19.2 kHz (33 ms) and smooths its reading over about four blocks; its
 * stability is the last block's distance to it.
 * The fixed parts of the screens (status-bar capsules, grid, needle scale)
 * are asset bitmaps drawn by gen_assets.py.
 *
 * Keys (UV-K5 and UV-K1): MENU next view, then AF Spectro · UP/DOWN SCOPE
 *   timebase, TUNE needle span (+-50, 20, 10 Hz) · * hold · 1 audio path STD / RAW · 2 speaker · 3 gain · 4 trigger edge ·
 *   5 persistence · 0 clear the persistence · EXIT quit (view, path, speaker,
 *   timebase, gain, edge, persistence and span saved).
 * The status bar shows RAW when the filters are off, a lock while held (else
 * a clipped wave while samples reach the ADC limits) and the speaker while
 * it is on. STD keeps the VFO's AF output and filters (USB
 * for USB, else FM, which AM also uses: its demodulator is REG_31 bit 0);
 * RAW turns the RX audio filters and the AFC off and, in FM only, selects the
 * discriminator bypass (REG_47 AF 9, as the radiosonde apps). The registers
 * are restored on exit, and the loader re-runs RADIO_SetupRegisters.
 */

