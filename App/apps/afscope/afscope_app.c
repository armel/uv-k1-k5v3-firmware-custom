/* ---- sampling ---- */
#define NMAX        640u       /* the trigger window, then 128 points x 4    */
#define TRIG_WIN    128u       /* samples searched for the trigger           */
#define TUNE_N      640u       /* TUNE: 33 ms ...                            */
#define TUNE_FSI    1u         /* ... at 19.2 kHz                            */
#define CYC_9K6     5000u      /* 48 MHz / 9.6 kHz, halved per rate step     */
#define CLIP_LO     (16 - 2048)
#define CLIP_HI     (4079 - 2048)
#define HYST_MIN    4
#define SPREAD_SH   3          /* FSK: periods 1/8 off the mean; a steady
                                  tone: fewer than 1/8 of them               */

/* ---- BK4829 ---- */
#define REG_0C      0x0C       /* bit 1: squelch open                         */
#define REG_2B      0x2B       /* bits 10:8 off: RX HPF 300, LPF 3k, de-emph. */
#define REG_31      0x31       /* bit 0: the AM demodulator, set by the VFO   */
#define REG_47      0x47       /* bits 11:8: AF output                        */
#define REG_73      0x73       /* bit 4: AFC disabled                         */
#define RAW_2B      0x0700u
#define RAW_73      0x0010u
#define AF_USB      5u         /* BK4819_AF_BASEBAND2, the firmware's USB AF  */
#define AF_BYPASS   9u         /* discriminator bypass, as the sonde apps     */

/* ---- the bottom lines: fixed fields, numbers right-aligned (characters) ---- */
#define F_FREQ      11u        /* "1750", "1227 / 2079", then "Hz": with PP and
                                  DC, the 32 characters of the line          */
#define F_PP        4u         /* up to 4095                                  */
#define F_DC        5u         /* "   +9" .. "-2048": DC ends on the right edge */
#define F_RF        8u         /* "145.500", "1300.000"                       */
#define F_RSSI      4u         /* "-130"                                      */

/* ---- screen (gen_assets.py draws the fixed parts with the same values) ---- */
#define TUNE_MID    63         /* needle scale centre, 1 px per span/50       */
#define SCALE_Y     19         /* needle scale line (fb y), the needle under  */
#define WAVE_MID    39u        /* TUNE waveform, +-7 px                       */
#define SCOPE_MID   19u        /* SCOPE trace, +-18 px                        */
#define PERS_LEN    (5u * 128u)  /* persistence: the trace lines 0-4         */
#define CFG_LEN     8u         /* view, raw, spk, tb, gain, edge, pers, span  */
#define C_TB        3u
#define TB_DEF      2u         /* 3.3 ms per division                         */

enum { V_SCOPE = 0, V_TUNE, V_COUNT };
enum { M_FM = 0, M_AM, M_USB };         /* the VFO's demodulation: the AF path */

#define SPANS       3u
/* the saved settings: their limits (a value at or over it reads as 0, the
 * timebase as TB_DEF) */
static const uint8_t CFG_LIM[CFG_LEN] = { V_COUNT, 2, 2, TB_COUNT, GAIN_COUNT, 2, 2, SPANS };
static const uint8_t SPAN[SPANS] = { 50, 20, 10 };      /* TUNE: +-Hz        */
/* timebases: the rate (9.6 kHz << fsi) and the samples per pixel (1 << dsh) */
static const uint8_t TB_FSI[TB_COUNT] = { 2, 1, 0, 0, 0 };
static const uint8_t TB_DSH[TB_COUNT] = { 0, 0, 0, 1, 2 };
/* REG_47's AF output per mode and path (mode * 2 + raw): FM, FM RAW (the
 * discriminator bypass), AM (the FM output, the AM demodulator on), AM RAW,
 * USB, USB RAW */
static const uint8_t AF_OUT[6] = { APP_AF_FM, AF_BYPASS, APP_AF_FM, APP_AF_FM, AF_USB, AF_USB };

/* The app state in one struct: one base address per function instead of a
 * literal per global. Bytes (the saved settings first, in cfg order), then
 * halfwords, then words, then the 64-bit twist sums carried for AF Spectro.
 * The loader zeroes the overlay (.bss) at every launch. */
static struct {
    union {                             /* the saved settings, cfg order */
        uint8_t set[CFG_LEN];
        struct { uint8_t view, raw, spk, tb, gain, edge, pers, span; };
    };
    uint8_t  prevKey, held, mode, fsi, dsh, dirty;
    bool     lcd;                       /* lcd_feed: a frame being sent       */
    uint8_t  frames;                    /* lcd_feed frames: K5Viewer every 16 */
    bool     running, steady;
    uint16_t r2B, r73, ftone, stab;
    int32_t  dc, mn, mx, pp, clip, fs, n, favg;
    int32_t  fmean, flo, fhi;           /* the counter's frequencies          */
    int32_t  cnt, t0, tl, p8;           /* crossings, first, last, mean period (Q8) */
    int32_t  nlo, nhi, slo, shi;        /* periods over / under p8: count, sum */
    int32_t  i0;                        /* the trigger sample                 */
    const app_api_t *A;
    int16_t  *smp;                      /* the block                          */
    uint8_t  *pbuf;                     /* persistence, then the TUNE fold    */
    char     *text;                     /* formatting buffer (app_main's stack) */
    uint64_t elo, ehi;                  /* AF Spectro's twist, passed through */
} g;
#define str g.text

