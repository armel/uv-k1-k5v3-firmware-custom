/*
 * AF Spectro - the spectrum of the demodulated RX audio, not of RF: the
 * BK4829 AF output, sampled on PA4 (the voice DAC pin) as APRS RX does, at
 * 9.6, 19.2 or 38.4 kHz. The spectral half of an instrument whose other half
 * is AF Scope (oscilloscope, tuner): MENU on the last view hands off to it.
 *   SPECTRO  the spectrum (0 to fs/2) with peak hold, the two main peaks and
 *            their level difference (TW; for Bell 202, the twist), a 16-row
 *            sonogram strip (1.3 s);
 *   SONO     the sonogram over the screen: 40 rows, 3.2 s.
 * Both sonograms scroll down, the newest row at the top. A row stays blank while the squelch is closed (STD only: in RAW its bit stays
 * closed): the hiss between packets would otherwise fill them as much as a
 * signal.
 * It names nothing it hears.
 *
 * Analysis (test/model.py is the reference, keep the two in step): blocks of
 * 256 samples, nothing else running while one is taken but, while the
 * speaker is on, the LCD bytes sent with the samples (lcd_feed); a Hann window,
 * a 256-point FFT in block floating point, levels in tenths of dB. A block is
 * a steady tone when its second peak lies 15 dB under the first: its
 * interpolated frequency counts for the MIN / MAX of the header. A frame is
 * about 80 ms of blocks (3, 6 or 12): the smoothed spectrum (1/4 of each
 * block) gives the bars, the peaks and the sonogram row, all scaled on its
 * mean level. Bell 202 AFSK (a plateau with 1200 and 2200 Hz near its peak,
 * over 800 and 2700 Hz) shows as 1200 / 2200 Hz, its twist the energy ratio
 * of the bands around them (+-2 bins), averaged over about 1.7 s of Bell 202
 * (the hiss between packets left out).
 * The fixed parts of the screens (status-bar capsules, axis) are asset
 * bitmaps drawn by gen_assets.py.
 *
 * Keys (UV-K5 and UV-K1): MENU next view, then AF Scope · UP/DOWN range of
 *   the bars and contrast of the sonogram (80, 60, 40 dB) · * hold · 1 audio
 *   path STD / RAW · 2 speaker · 3 sample rate · 0 clear (peak hold,
 *   sonogram, MIN / MAX, twist) · EXIT quit (view, path, speaker,
 *   rate and range saved).
 * The status bar shows RAW when the filters are off, a lock while held (else
 * a clipped wave while samples reach the ADC limits) and the speaker while
 * it is on. STD keeps the VFO's AF output and filters (USB
 * for USB, else FM, which AM also uses: its demodulator is REG_31 bit 0);
 * RAW turns the RX audio filters and the AFC off and, in FM only, selects the
 * discriminator bypass (REG_47 AF 9, as the radiosonde apps). The registers
 * are restored on exit, and the loader re-runs RADIO_SetupRegisters.
 */

