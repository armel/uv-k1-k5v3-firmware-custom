/* ---- sampling ---- */
#define N           256u
#define BINS        128u
#define CYC_9K6     5000u      /* 48 MHz / 9.6 kHz, halved per rate step     */
#define BLOCKS_9K6  3u         /* blocks per frame at 9.6 kHz: 80 ms         */
#define FS_COUNT    3u
#define CLIP_LO     (16 - 2048)
#define CLIP_HI     (4079 - 2048)

/* ---- analysis (test/model.py) ---- */
#define FFT_LIMIT   8192       /* below it a butterfly stage cannot overflow */
#define PEAK_LO     2u
#define PEAK_HI     125u
#define PEAK_GUARD  6u         /* bins between the two peaks                 */
#define PURE_DB     150        /* a steady tone: the second peak 15 dB under */
#define TWO_DB      300        /* two tones: the second within 30 dB ...     */
#define OVER_DB     120        /* ... both 12 dB over the mean level, ...    */
#define VALLEY_DB   100        /* ... and 10 dB over the level between them  */
#define FLOOR_DB    50         /* bars: the mean level 5 dB over the bottom  */
#define BELL_DB     150        /* Bell 202: 1200, 2200 Hz 15 dB under the peak, */
#define EDGE_DB     60         /* 6 dB over 800 and 2700 Hz (voice is not)   */
#define BELL_HOLD   8u         /* frames a detection lasts                   */
#define BAND        2u         /* twist bands: +-2 bins                       */
#define TW_SHIFT    6u         /* twist average: 1/64 per block at 9.6 kHz    */

/* ---- BK4829 ---- */
#define REG_0C      0x0C       /* bit 1: squelch open                         */
#define REG_2B      0x2B       /* bits 10:8 off: RX HPF 300, LPF 3k, de-emph. */
#define REG_31      0x31       /* bit 0: the AM demodulator, set by the VFO   */
#define REG_47      0x47       /* bits 11:8: AF output                        */
#define REG_73      0x73       /* bit 4: AFC disabled                         */
#define RAW_2B      0x0700u
#define RAW_73      0x0010u
#define AF_USB      5u         /* BK4819_AF_BASEBAND2, the firmware's USB AF  */
#define AF_BYPASS   9u         /* discriminator bypass, as the sonde apps     */

/* ---- screen (gen_assets.py draws the fixed parts with the same values) ---- */
#define BAR_BASE    31u        /* SPECTRO bars, 24 px up to y = 8             */
#define BAR_H       24
#define SON_PAGES   5u         /* sonogram: 40 rows ...                       */
#define STRIP_PAGES 2u         /* ... and SPECTRO's strip, 16 rows            */
#define CFG_LEN     5u         /* view, raw, spk, fsi, range                  */

enum { V_SPECTRO = 0, V_SONO, V_COUNT };
enum { M_FM = 0, M_AM, M_USB };         /* the VFO's demodulation: the AF path */

/* The quarter sine table, then the mantissa of lg(): one read at launch. */
_Static_assert(LOGT == SINQ + SINQ_LEN && LOGT_LEN == 32u, "LOGT must follow SINQ");
#define LOGT_TAB    ((const uint8_t *)(g.sinq + SINQ_LEN / 2u))
#define RANGES      3u
/* the saved settings: their limits (a value at or over it reads as 0, the
 * range as 1: 60 dB) */
static const uint8_t CFG_LIM[CFG_LEN] = { V_COUNT, 2, 2, FS_COUNT, RANGES };
static const uint8_t RANGE[RANGES] = { 80, 60, 40 };    /* dB over the bars   */
static const uint8_t KHI[FS_COUNT] = { 59, 29, 15 };    /* 2200 Hz bin        */
/* REG_47's AF output per mode and path (mode * 2 + raw): FM, FM RAW (the
 * discriminator bypass), AM (the FM output, the AM demodulator on), AM RAW,
 * USB, USB RAW */
static const uint8_t AF_OUT[6] = { APP_AF_FM, AF_BYPASS, APP_AF_FM, APP_AF_FM, AF_USB, AF_USB };

/* The app state in one struct: one base address per function instead of a
 * literal per global. Bytes (the saved settings first, in cfg order), then
 * halfwords, then words, then the 64-bit sums. The loader zeroes the overlay
 * (.bss) at every launch. */
static struct {
    union {                             /* the saved settings, cfg order */
        uint8_t set[CFG_LEN];
        struct { uint8_t view, raw, spk, fsi, range; };
    };
    uint8_t  prevKey, held, fresh, mode, kHi, bellFor, sq;   /* sq: squelch open */
    uint8_t  sono;                      /* frame parity: dotted rows          */
    bool     lcd;                       /* lcd_feed: a frame being sent       */
    uint8_t  frames;                    /* lcd_feed frames: K5Viewer every 16 */
    bool     running, two, bell;
    uint16_t r2B, r73, tmin, tmax;
    int32_t  clip, mean, l1, l2, f1, f2, fs;
    const app_api_t *A;
    int16_t  *smp, *S, *im;             /* samples/FFT real, smoothed, FFT imag */
    uint8_t  *hold;                     /* peak hold (px), then the sonogram   */
    const int16_t *sinq;                /* then LOGT_TAB                      */
    char     *text;                     /* formatting buffer (app_main's stack) */
    uint64_t elo, ehi;                  /* Bell 202 band energies             */
} g;
#define str g.text
#define SON (g.hold + BINS)             /* sonogram: SON_PAGES after the hold, */
#define STRIP (SON + SON_PAGES * BINS)  /* then the strip                      */

