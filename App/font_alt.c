void FONT_DrawBigGlyphWithVariant(uint8_t variant, uint8_t glyph,
                                  uint8_t *top, uint8_t *bottom)
{
    const uint8_t family = variant / FONT_BIG_DIGITS_COUNT;
    const uint8_t first_lowercase = (uint8_t)('a' - ' ' - 1);

    if (family == FONT_TEXT_BLOCK)
    {
        uint8_t source[FONT_SMALL_WIDTH];

        FW_ASSETS_Read(gFontSmallBlock[glyph], source, sizeof(source));
        top[0] = 0;
        bottom[0] = 0;

        for (uint8_t x = 0; x < FONT_SMALL_WIDTH; x++)
        {
            uint16_t expanded = 0;

            for (uint8_t y = 0; y < 8u; y++)
            {
                if ((source[x] & (1u << y)) != 0u)
                    expanded |= (uint16_t)(3u << (y * 2u));
            }

            top[x + 1u] = (uint8_t)expanded;
            bottom[x + 1u] = (uint8_t)(expanded >> 8);
        }
        return;
    }

    if (family == FONT_TEXT_SMALL_CAPS &&
        glyph >= first_lowercase && glyph < first_lowercase + 26u)
    {
        const uint8_t small_caps = glyph - first_lowercase;

        FW_ASSETS_Read(gFontBigSmallCaps[small_caps], top, FONT_BIG_WIDTH);
        FW_ASSETS_Read(gFontBigSmallCaps[small_caps] + FONT_BIG_WIDTH,
                       bottom, FONT_BIG_WIDTH);
        return;
    }

    FONT_DrawBigGlyph(glyph, top, bottom);
}

