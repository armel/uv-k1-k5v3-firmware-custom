"""Convert an 8-bit RGB/RGBA PNG to raw little-endian RGB565 for LVGL.

Used by main/CMakeLists.txt to embed the portrait skin. Only the standard
library is needed, so it runs in the ESP-IDF Python environment. An ordered
4x4 dither keeps the skin gradients free of RGB565 banding.

With --asm, an assembler file is also written that pulls the raw data into
.rodata with .incbin and exports <symbol>_start / <symbol>_end. This avoids
ESP-IDF's EMBED_FILES path, which hex-encodes the file through CMake regular
expressions and is very slow for a 1.8 MB image.
"""

import argparse
import sys
from array import array
from pathlib import Path

from gen_uv_k1_skin import read_png_rgb

BAYER4 = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))


def convert(src, dst, expected_size=None):
    width, height, rows = read_png_rgb(src)
    if expected_size and (width, height) != tuple(expected_size):
        raise ValueError(f'{src}: {width}x{height}, expected {expected_size[0]}x{expected_size[1]}')

    pixels = array('H')
    for y, row in enumerate(rows):
        bayer = BAYER4[y & 3]
        for x in range(width):
            r, g, b = row[3 * x], row[3 * x + 1], row[3 * x + 2]
            t = bayer[x & 3]
            r5 = min(31, (r + (t >> 1)) >> 3)
            g6 = min(63, (g + (t >> 2)) >> 2)
            b5 = min(31, (b + (t >> 1)) >> 3)
            pixels.append((r5 << 11) | (g6 << 5) | b5)
    if sys.byteorder == 'big':
        pixels.byteswap()
    Path(dst).write_bytes(pixels.tobytes())


def write_asm(asm_path, data_path, symbol):
    data = Path(data_path).resolve().as_posix()
    Path(asm_path).write_text(
        f'/* Generated by png_to_rgb565.py: {Path(data_path).name} embedded with .incbin. */\n'
        '    .section .rodata.embedded\n'
        '    .balign 4\n'
        f'    .global {symbol}_start\n'
        f'{symbol}_start:\n'
        f'    .incbin "{data}"\n'
        f'    .global {symbol}_end\n'
        f'{symbol}_end:\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('input', help='source PNG')
    parser.add_argument('output', help='raw RGB565 output')
    parser.add_argument('--size', type=int, nargs=2, metavar=('WIDTH', 'HEIGHT'),
                        help='fail unless the PNG has this size')
    parser.add_argument('--asm', help='also write an assembler file embedding the output')
    parser.add_argument('--symbol', default='skin_rgb565',
                        help='symbol prefix for --asm (default: %(default)s)')
    args = parser.parse_args()

    convert(args.input, args.output, args.size)
    if args.asm:
        write_asm(args.asm, args.output, args.symbol)


if __name__ == '__main__':
    main()
