#!/usr/bin/env python3
"""Generate app/alert_stations_gen.h - a compact flash-resident ALERT id -> station table.

The single source of truth is the MegaNet repository (github.com/cdomotor-g/MegaNet).
Nothing from MegaNet is copied into this repository except the generated header, which is
a build artefact regenerated by CI.

Sources consumed:
  stations.json                  station records with sensors[] / alert_ids{}
  data/All 2021 Working 2.txt    the legacy ALERT "address location file" (UTF-16LE)
  data/ALL_REPEATERS.csv         repeater -> BoM network -> pass (address) ranges

Usage:
  python3 tools/gen_stations.py [--meganet-dir DIR] [--filter stations.filter] ...
  python3 tools/gen_stations.py --list-networks
  python3 tools/gen_stations.py --check          # CI: fail if the header is stale

Standard library only.
"""

