def _decode_utf16(data):
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return data.decode("utf-16")
    try:
        return data.decode("utf-16-le")
    except UnicodeDecodeError:
        return data.decode("utf-8", "replace")


def _fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "quansheng-alert-gen"})
    with urllib.request.urlopen(req, timeout=60) as fh:
        return fh.read()


class Sources(object):
    def __init__(self, stations, addresses, repeaters, sha, short_sha, date):
        self.stations = stations       # parsed json
        self.addresses = addresses     # decoded text
        self.repeaters = repeaters     # decoded text
        self.sha = sha
        self.short_sha = short_sha
        self.date = date


def _git(dirpath, *args):
    try:
        out = subprocess.run(
            ["git", "-C", dirpath] + list(args),
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=True,
        )
        return out.stdout.decode("utf-8", "replace").strip()
    except Exception:
        return ""


def load_sources(meganet_dir, ref):
    if meganet_dir:
        base = os.path.abspath(meganet_dir)
        with open(os.path.join(base, STATIONS_JSON), "rb") as fh:
            stations = json.loads(fh.read().decode("utf-8-sig"))
        with open(os.path.join(base, ADDRESS_FILE), "rb") as fh:
            addresses = _decode_utf16(fh.read())
        with open(os.path.join(base, REPEATERS_CSV), "rb") as fh:
            repeaters = fh.read().decode("utf-8-sig")
        sha = _git(base, "rev-parse", "HEAD") or ref
        short = _git(base, "rev-parse", "--short", "HEAD") or ref
        # commit date keeps the header byte-stable between runs (important for --check)
        date = _git(base, "log", "-1", "--format=%cd", "--date=format-local:%Y-%m-%d")
        if not date:
            date = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        return Sources(stations, addresses, repeaters, sha, short, date)

    raw = RAW_BASE.format(ref=ref)
    stations = json.loads(_fetch(raw + STATIONS_JSON).decode("utf-8-sig"))
    addresses = _decode_utf16(_fetch(raw + ADDRESS_FILE_URL))
    repeaters = _fetch(raw + REPEATERS_CSV).decode("utf-8-sig")
    sha, short, date = ref, ref, datetime.now(timezone.utc).strftime("%Y-%m-%d")
    try:
        info = json.loads(_fetch(API_COMMIT.format(ref=ref)).decode("utf-8"))
        sha = info.get("sha") or ref
        short = sha[:7]
        iso = (info.get("commit", {}).get("committer", {}) or {}).get("date")
        if iso:
            date = iso[:10]
    except (urllib.error.URLError, urllib.error.HTTPError, ValueError, KeyError):
        pass  # offline / rate limited - fall back to the ref itself
    return Sources(stations, addresses, repeaters, sha, short, date)


