class Filter(object):
    def __init__(self):
        self.include = []   # (kind, arg)
        self.exclude = []

    @property
    def empty(self):
        return not self.include

    @staticmethod
    def parse(path):
        f = Filter()
        with open(path, "r", encoding="utf-8") as fh:
            for lineno, line in enumerate(fh, 1):
                line = line.split("#", 1)[0].strip()
                if not line:
                    continue
                target = f.include
                if line.lower().startswith("exclude "):
                    target = f.exclude
                    line = line[len("exclude "):].strip()
                parts = line.split(None, 1)
                verb = parts[0].lower()
                arg = parts[1].strip() if len(parts) > 1 else ""
                if verb == "all":
                    target.append(("all", None))
                elif verb == "range":
                    m = re.match(r"^(\d+)\s*-\s*(\d+)$", arg)
                    if not m:
                        raise SystemExit("%s:%d: bad range %r" % (path, lineno, arg))
                    lo, hi = int(m.group(1)), int(m.group(2))
                    target.append(("range", (min(lo, hi), max(lo, hi))))
                elif verb == "id":
                    target.append(("id", int(arg)))
                elif verb in ("network", "catchment", "station"):
                    if not arg:
                        raise SystemExit("%s:%d: %s needs an argument" % (path, lineno, verb))
                    target.append((verb, arg.lower()))
                else:
                    raise SystemExit("%s:%d: unknown directive %r" % (path, lineno, verb))
        return f

    @staticmethod
    def _match(rule, rec):
        kind, arg = rule
        if kind == "all":
            return True
        if kind == "range":
            return arg[0] <= rec.aid <= arg[1]
        if kind == "id":
            return rec.aid == arg
        if kind == "network":
            return any(arg in n.lower() for n in rec.networks)
        if kind == "catchment":
            return any(arg in c.lower() for c in rec.catchments)
        if kind == "station":
            return arg in rec.full_name.lower() or arg in rec.name.lower()
        return False

    def keep(self, rec):
        if not any(self._match(r, rec) for r in self.include):
            return False
        return not any(self._match(r, rec) for r in self.exclude)


