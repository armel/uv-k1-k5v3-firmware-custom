def _same_site(a, b):
    """Two cleaned names that only differ by a trailing qualifier / 13-char truncation."""
    return a.startswith(b) or b.startswith(a)


def dedupe(records):
    """ALERT addresses are unique only per region. Keep the first claimant.

    Order is (source priority, source order, address) so the result is deterministic.
    Returns (kept records, collisions) where collisions is a list of
    (aid, winner name, [loser names]) covering only genuine conflicts - a loser whose
    name is a prefix variant of the winner is the same site described by both sources
    and is counted in `benign` instead.
    """
    ordered = sorted(records, key=lambda r: (r.pri, r.order, r.aid))
    winner = {}
    losers = {}
    benign = 0
    for rec in ordered:
        if rec.aid in winner:
            if rec.name != winner[rec.aid].name:
                if _same_site(rec.name, winner[rec.aid].name):
                    benign += 1
                else:
                    losers.setdefault(rec.aid, []).append(rec.name)
            continue
        winner[rec.aid] = rec
    collisions = []
    for aid in sorted(losers):
        seen = []
        for n in losers[aid]:
            if n not in seen and not _same_site(n, winner[aid].name):
                seen.append(n)
        if seen:
            collisions.append((aid, winner[aid].name, seen))
    return [winner[a] for a in sorted(winner)], collisions, benign


class Site(object):
    __slots__ = ("base", "kinds", "name", "members")

    def __init__(self, base, name):
        self.base = base
        self.name = name
        self.kinds = 0
        self.members = []  # (aid, kind)

    def add(self, aid, kind):
        self.kinds |= (kind & 7) << (3 * (aid - self.base))
        self.members.append((aid, kind))


def build_sites(records):
    """Group records into sites of up to 5 consecutive addresses (base..base+4).

    A site takes the smallest remaining address of its group as the base and absorbs the
    group's further addresses that land inside the window. The walk is over the globally
    sorted address list rather than one group at a time, so a site is always a contiguous
    slice of that list and can never claim an address at or beyond the next site's base.
    That matters: the C side binary-searches for the greatest base_id <= id, so a site
    whose window straddled another site's base would make those addresses unreachable
    (2,156 "Three Mile Br" was one of 12 such addresses before this cut was added).
    """
    recs = sorted(records, key=lambda r: (r.aid, r.group))
    sites = []
    cur = None
    cur_group = None
    for rec in recs:
        if cur is None or rec.group != cur_group or rec.aid >= cur.base + SITE_SPAN:
            cur = Site(rec.aid, rec.name)
            cur_group = rec.group
            sites.append(cur)
        cur.add(rec.aid, rec.kind)
    return sites


def build_pool(sites):
    """De-duplicated name pool. Returns (offsets by name, ordered names, byte length)."""
    offsets = {}
    order = []
    total = 0
    for site in sites:
        if site.name not in offsets:
            offsets[site.name] = total
            order.append(site.name)
            total += len(site.name) + 1
    return offsets, order, total


def table_bytes(sites):
    _, _, pool = build_pool(sites)
    return SITE_BYTES * len(sites) + pool


def cost_of(records):
    if not records:
        return 0, 0, 0
    sites = build_sites(records)
    return len(sites), len(records), table_bytes(sites)


