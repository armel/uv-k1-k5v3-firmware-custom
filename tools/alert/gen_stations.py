class Record(object):
    """One ALERT address with everything needed to filter and group it."""

    __slots__ = ("aid", "kind", "name", "full_name", "group", "pri", "order",
                 "networks", "catchments")

    def __init__(self, aid, kind, name, full_name, group, pri, order,
                 networks, catchments):
        self.aid = aid
        self.kind = kind
        self.name = name
        self.full_name = full_name
        self.group = group
        self.pri = pri
        self.order = order
        self.networks = networks
        self.catchments = catchments


ALERT_IDS_KIND = [("rainfall", KIND_RAIN), ("water_level", KIND_LEVEL),
                  ("battery", KIND_BATT)]


def parse_repeaters(text):
    """-> {network name: [(lo, hi), ...]} from the BoM Network / pass range columns."""
    nets = {}
    reader = csv.DictReader(io.StringIO(text))

    def num(v):
        v = (v or "").strip()
        if not v:
            return None
        try:
            return int(float(v))
        except ValueError:
            return None

    for row in reader:
        net = (row.get("BoM Network") or "").strip()
        if not net:
            continue
        for i in range(1, 9):
            lo = num(row.get("Pass low %d" % i))
            hi = num(row.get("Pass high %d" % i))
            if lo is None or hi is None:
                continue
            if lo > hi:
                lo, hi = hi, lo
            nets.setdefault(net, []).append((lo, hi))
    for net in nets:
        nets[net] = sorted(set(nets[net]))
    return nets


def networks_for_id(aid, repeater_nets):
    return set(net for net, ranges in repeater_nets.items()
               if any(lo <= aid <= hi for lo, hi in ranges))


def parse_stations_json(doc, repeater_nets):
    """One Record per (station, alert address). Priority 0 - wins over the address file."""
    net_name = {n["id"]: n.get("name", n["id"]) for n in doc.get("radio_networks", [])}
    cat_name = {c["id"]: c.get("name", c["id"]) for c in doc.get("catchments", [])}
    records = []
    order = 0
    for st in doc.get("stations", []):
        raw = (st.get("name") or st.get("id") or "").strip()
        if not raw:
            continue
        kinds = {}  # aid -> kind, first non-OTHER wins
        for sensor in st.get("sensors") or []:
            aid = sensor.get("alert_id")
            if not isinstance(aid, int):
                continue
            k = kind_of(sensor.get("type") or "")
            if aid not in kinds or (kinds[aid] == KIND_OTHER and k != KIND_OTHER):
                kinds[aid] = k
        for key, k in ALERT_IDS_KIND:
            aid = (st.get("alert_ids") or {}).get(key)
            if not isinstance(aid, int):
                continue
            if aid not in kinds or (kinds[aid] == KIND_OTHER and k != KIND_OTHER):
                kinds[aid] = k

        st_nets = set()
        for nid in st.get("radio_network_ids") or []:
            st_nets.add(nid)
            st_nets.add(net_name.get(nid, nid))
        cats = set()
        for cid in st.get("catchment_ids") or []:
            cats.add(cid)
            cats.add(cat_name.get(cid, cid))

        group = "S:" + (st.get("id") or raw) + ":%d" % order
        name = clean_name(raw)
        if not name:
            continue
        for aid in sorted(kinds):
            if not (0 < aid <= MAX_ALERT_ID):
                continue
            nets = set(st_nets) | networks_for_id(aid, repeater_nets)
            records.append(Record(aid, kinds[aid] or KIND_OTHER, name, raw, group,
                                  0, order, nets, cats))
        order += 1
    return records


ADDR_LINE = re.compile(r"^\s*(\d+)\s+(.*\S)")


def parse_address_file(text, repeater_nets):
    """Records from the legacy address file. Priority 1 - fallback only."""
    rows = []
    for line in text.splitlines():
        if not line.startswith(" "):
            continue  # the file's own convention: comments do not start with a space
        m = ADDR_LINE.match(line)
        if not m:
            continue
        aid = int(m.group(1))
        if not (0 < aid <= MAX_ALERT_ID):
            continue
        rows.append((aid, m.group(2).strip()))
    rows.sort(key=lambda r: r[0])

    records = []
    prev_name = None
    gidx = 0
    for order, (aid, raw) in enumerate(rows):
        name = clean_name(raw)
        if not name:
            continue
        # consecutive rows sharing the cleaned name prefix belong to one site group
        if name != prev_name:
            gidx += 1
            prev_name = name
        group = "A:%s:%d" % (name, gidx)
        kind = suffix_kind(split_suffix(raw)[1], raw)
        nets = networks_for_id(aid, repeater_nets)
        records.append(Record(aid, kind, name, raw, group, 1, order, nets, set()))
    return records


