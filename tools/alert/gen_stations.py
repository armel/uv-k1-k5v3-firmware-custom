def network_costs(records, repeater_nets, doc):
    """[(name, station count, address count, sites, bytes)] sorted by bytes desc."""
    names = set(repeater_nets)
    for n in doc.get("radio_networks", []):
        names.add(n.get("name", n["id"]))
    rows = []
    for name in sorted(names):
        low = name.lower()
        sel = [r for r in records if any(low in n.lower() for n in r.networks)]
        if not sel:
            rows.append((name, 0, 0, 0, 0))
            continue
        sites, addrs, byts = cost_of(sel)
        stations = len(set(r.group for r in sel))
        rows.append((name, stations, addrs, sites, byts))
    rows.sort(key=lambda r: (-r[4], r[0]))
    return rows


def catchment_costs(records, doc):
    names = set()
    for c in doc.get("catchments", []):
        names.add(c.get("name", c["id"]))
    rows = []
    for name in sorted(names):
        low = name.lower()
        sel = [r for r in records if any(low in c.lower() for c in r.catchments)]
        if not sel:
            continue
        sites, addrs, byts = cost_of(sel)
        rows.append((name, len(set(r.group for r in sel)), addrs, sites, byts))
    rows.sort(key=lambda r: (-r[4], r[0]))
    return rows


def print_table(title, rows, limit=None):
    print("")
    print(title)
    print("  %-28s %8s %8s %8s %9s" % ("name", "stations", "addrs", "sites", "bytes"))
    for row in (rows[:limit] if limit else rows):
        print("  %-28s %8d %8d %8d %9d" % row)


