def main(argv=None):
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--meganet-dir", default=os.environ.get("MEGANET_DIR"),
                    help="local MegaNet checkout (default: $MEGANET_DIR, else fetch)")
    ap.add_argument("--meganet-ref", default="main", help="git ref to fetch (default main)")
    ap.add_argument("--filter", default=os.path.join(here, "stations.filter"))
    ap.add_argument("--out", default=os.path.join(here, "app", "alert_stations_gen.h"))
    ap.add_argument("--max-bytes", type=int, default=6400)
    ap.add_argument("--list-networks", action="store_true",
                    help="print per-network / per-catchment costs and exit")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the output would change (for CI)")
    ap.add_argument("--provenance-out", default=None,
                    help="write the MegaNet commit and date here as JSON. That "
                         "provenance is deliberately kept out of the generated "
                         "header, because anything in the header ends up in the "
                         "firmware image and would rewrite it on every unrelated "
                         "MegaNet push")
    args = ap.parse_args(argv)

    src = load_sources(args.meganet_dir, args.meganet_ref)
    repeater_nets = parse_repeaters(src.repeaters)
    records = (parse_stations_json(src.stations, repeater_nets)
               + parse_address_file(src.addresses, repeater_nets))
    universe, collisions, benign = dedupe(records)

    if args.list_networks:
        print("MegaNet %s @ %s (%s)" % (REPO, src.short_sha, src.date))
        sites, addrs, byts = cost_of(universe)
        print("Universe: %d sites, %d addresses, %d bytes (everything)"
              % (sites, addrs, byts))
        print_table("Networks (radio_networks + ALL_REPEATERS.csv pass ranges):",
                    network_costs(universe, repeater_nets, src.stations))
        print_table("Catchments:", catchment_costs(universe, src.stations))
        return 0

    filt = Filter.parse(args.filter)
    if filt.empty:
        raise SystemExit("%s contains no include directives - nothing to generate"
                         % args.filter)
    selected = [r for r in universe if filt.keep(r)]
    if not selected:
        raise SystemExit("filter %s selected no addresses" % args.filter)

    sites = build_sites(selected)
    bases = [s.base for s in sites]
    assert bases == sorted(bases), "sites must be sorted by base_id"
    assert len(set(bases)) == len(bases), "duplicate base_id in table"

    text = render_header(sites, src, os.path.basename(args.filter))
    total = table_bytes(sites)
    addresses = sum(len(s.members) for s in sites)

    if args.provenance_out:
        m = re.search(r"Data: (\w+)", text)
        os.makedirs(os.path.dirname(os.path.abspath(args.provenance_out)) or ".", exist_ok=True)
        with open(args.provenance_out, "w") as fh:
            json.dump({"repo": REPO, "commit": src.short_sha, "commit_full": src.sha,
                       "date": src.date, "filter": os.path.basename(args.filter),
                       "sites": len(sites), "addresses": addresses, "bytes": total,
                       "fingerprint": m.group(1) if m else None}, fh, indent=2)
            fh.write("\n")
        print("Wrote %s" % args.provenance_out)

    net_rows = network_costs(selected, repeater_nets, src.stations)

    if collisions:
        print("WARNING: %d ALERT addresses are claimed by more than one site (ALERT "
              "addresses are only unique per region). Kept the first by source priority "
              "(stations.json before the address file):" % len(collisions))
        for aid, win, others in collisions[:30]:
            print("  %5d  kept %-13s  dropped %s" % (aid, win, ", ".join(others[:3])))
        if len(collisions) > 30:
            print("  ... and %d more" % (len(collisions) - 30))
    if benign:
        print("(%d further duplicate addresses were the same site named slightly "
              "differently by the two sources; not listed.)" % benign)

    print("")
    print("MegaNet %s @ %s (%s)   filter: %s"
          % (REPO, src.short_sha, src.date, args.filter))
    print("Sites: %d   Addresses covered: %d   Table bytes: %d (limit %d)"
          % (len(sites), addresses, total, args.max_bytes))
    print_table("Top networks by cost (within the current filter):", net_rows, limit=15)

    if total > args.max_bytes:
        print("")
        print("ERROR: table is %d bytes, %d over the --max-bytes limit of %d."
              % (total, total - args.max_bytes, args.max_bytes))
        print("Trim %s - drop or narrow the most expensive networks listed above."
              % args.filter)
        return 2

    if args.check:
        try:
            with open(args.out, "r", encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            print("")
            print("ERROR: %s is out of date; re-run tools/gen_stations.py" % args.out)
            return 1
        print("")
        print("%s is up to date." % args.out)
        return 0

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("")
    print("Wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
