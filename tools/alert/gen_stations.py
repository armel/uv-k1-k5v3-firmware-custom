# --------------------------------------------------------------------------------------
# constants
# --------------------------------------------------------------------------------------

REPO = "cdomotor-g/MegaNet"
RAW_BASE = "https://raw.githubusercontent.com/" + REPO + "/{ref}/"
API_COMMIT = "https://api.github.com/repos/" + REPO + "/commits/{ref}"

STATIONS_JSON = "stations.json"
ADDRESS_FILE = "data/All 2021 Working 2.txt"
ADDRESS_FILE_URL = "data/All%202021%20Working%202.txt"
REPEATERS_CSV = "data/ALL_REPEATERS.csv"

# kind codes - must match the comment block emitted into the header and the C decoder
KIND_NONE = 0
KIND_RAIN = 1
KIND_LEVEL = 2
KIND_BATT = 3
KIND_REP = 4
KIND_OTHER = 5
KIND_CHECK = 6
KIND_NAME = {
    KIND_NONE: "NONE",
    KIND_RAIN: "RAIN",
    KIND_LEVEL: "LEVEL",
    KIND_BATT: "BATT",
    KIND_REP: "REP",
    KIND_OTHER: "OTHER",
    KIND_CHECK: "CHECK",
}

SITE_SPAN = 5          # a site covers base .. base+4
SITE_BYTES = 6         # sizeof(AlertSite_t)
MAX_ALERT_ID = 0x1FFF  # 13-bit ALERT address
NAME_MAX = 13
NAME_ALLOWED = re.compile(r"[^A-Z0-9 /.\-&']")

# Ordered classification rules. "RN/Rep" and "Rain/Rep" must land on RAIN, so rain wins
# over repeater; battery/volt is tested first because "Batt" never means anything else.
KIND_RULES = [
    (re.compile(r"batt|volt", re.I), KIND_BATT),
    (re.compile(r"rain", re.I), KIND_RAIN),
    (re.compile(r"level|stage|ahd|height|river|\bRV\b", re.I), KIND_LEVEL),
    (re.compile(r"repeat|\bRep\b", re.I), KIND_REP),
    (re.compile(r"check|chk", re.I), KIND_CHECK),
]

# Trailing tokens that are not part of the site name: the sensor-kind markers used by the
# address file, plus the "AL"/"ALERT" marker most MegaNet names carry ("Loudoun Br AL").
SUFFIX_TOKEN = re.compile(
    r"^(batt(ery)?|rn|rain|rv|river|rep(eater)?[0-9]?|rptr|r/rep|rn/rep|rain/rep|"
    r"chk|check|v|volts?|temp|rh|lvl|stage|ahd|al|alert)$",
    re.I,
)

# Address-file suffix tokens are terse and do not all fall out of KIND_RULES ("RN" is
# rain, not other; "RN/Rep" is rain, not repeater), so map the known ones explicitly.
SUFFIX_KIND = {
    "rn": KIND_RAIN, "rain": KIND_RAIN, "rn/rep": KIND_RAIN, "rain/rep": KIND_RAIN,
    "r/rep": KIND_RAIN,
    "rv": KIND_LEVEL, "river": KIND_LEVEL, "lvl": KIND_LEVEL, "stage": KIND_LEVEL,
    "ahd": KIND_LEVEL,
    "batt": KIND_BATT, "battery": KIND_BATT, "v": KIND_BATT, "volt": KIND_BATT,
    "volts": KIND_BATT,
    "rep": KIND_REP, "rep1": KIND_REP, "rep2": KIND_REP, "repeater": KIND_REP,
    "rptr": KIND_REP,
    "chk": KIND_CHECK, "check": KIND_CHECK,
    "temp": KIND_OTHER, "rh": KIND_OTHER,
}
# "AL"/"ALERT" says nothing about the sensor - never let it decide the kind.
KIND_NEUTRAL = ("al", "alert")
KIND_NEUTRAL_UPPER = frozenset(t.upper() for t in KIND_NEUTRAL)


def kind_of(text):
    """Classify a sensor type string / name suffix into a kind code."""
    if not text:
        return KIND_OTHER
    for rx, code in KIND_RULES:
        if rx.search(text):
            return code
    return KIND_OTHER


# --------------------------------------------------------------------------------------
# name cleaning
# --------------------------------------------------------------------------------------

def split_suffix(name):
    """Split trailing marker tokens off a name.

    'Caniaview RN/Rep' -> ('Caniaview', ['RN/Rep']);  'Loudoun Br AL' -> ('Loudoun Br', ['AL']).
    """
    parts = name.split()
    tail = []
    while len(parts) > 1 and SUFFIX_TOKEN.match(parts[-1]):
        tail.append(parts.pop())
    tail.reverse()
    return " ".join(parts), tail


def strip_kind_suffix(name):
    """Drop trailing marker tokens: 'Caniaview RN/Rep' -> 'Caniaview'."""
    return split_suffix(name)[0]


def suffix_kind(tokens, whole):
    """Kind implied by an address-file name's trailing tokens."""
    for tok in tokens:
        low = tok.lower()
        if low in KIND_NEUTRAL:
            continue
        if low in SUFFIX_KIND:
            return SUFFIX_KIND[low]
    meaningful = [t for t in tokens if t.lower() not in KIND_NEUTRAL]
    return kind_of(" ".join(meaningful)) if meaningful else kind_of(whole)


def clean_name(name):
    """Uppercase ASCII, restricted charset, whitespace collapsed, truncated to 13."""
    s = strip_kind_suffix(name)
    s = s.upper()
    # fold anything non-ASCII to a space before the charset filter
    s = s.encode("ascii", "replace").decode("ascii").replace("?", " ")
    s = NAME_ALLOWED.sub(" ", s)
    # The "AL"/"ALERT" marker also turns up mid-name, ahead of a parenthesised qualifier
    # ("Walls Camp AL (Pacific Haven)"), where the trailing strip above cannot reach it.
    # Drop it as a standalone token wherever it appears - it never carries any meaning.
    words = [w for w in s.split() if w not in KIND_NEUTRAL_UPPER]
    if not words:
        words = s.split()
    s = " ".join(words)
    s = s[:NAME_MAX].rstrip()
    return s


